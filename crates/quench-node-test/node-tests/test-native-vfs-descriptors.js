'use strict';
const assert = require('assert');
const vfs = require('node:vfs');
const descriptors = require('internal/vfs/fd');
const first = vfs.create(), second = vfs.create();
first.writeFileSync('/x', 'abcdef');
second.writeFileSync('/x', '123456');
const a = first.openSync('/x', 'r+');
const b = second.openSync('/x', 'r+');
const record = descriptors.getVirtualFd(a);
assert.notStrictEqual(a, b);
assert.strictEqual(record.fd, a);
assert.strictEqual(record.getAsyncId(), a);
assert.notStrictEqual(a & descriptors.VFS_FD_MASK, 0);
assert.strictEqual(descriptors, require('internal/vfs/fd'));
const bytes = Buffer.alloc(2);
assert.strictEqual(first.readSync(a, bytes, 0, 2, null), 2);
assert.strictEqual(bytes.toString(), 'ab');
assert.strictEqual(record.entry.position, 2);
record.entry.position = 3;
assert.strictEqual(first.writeSync(a, Buffer.from('XY'), 0, 2, null), 2);
assert.strictEqual(first.readFileSync('/x', 'utf8'), 'abcXYf');
assert.strictEqual(second.readFileSync('/x', 'utf8'), '123456');
assert.strictEqual(record.entry.position, 5);
first.closeSync(a);
assert.strictEqual(descriptors.getVirtualFd(a), undefined);
assert.notStrictEqual(descriptors.getVirtualFd(b), undefined);
second.closeSync(b);
assert.strictEqual(descriptors.closeVirtualFd(b), false);
console.log('native-vfs-descriptors-ok');
