const cluster = require('node:cluster');
const domain = require('node:domain');
const v8 = require('node:v8');
if (!cluster.isPrimary || cluster.isWorker || cluster.worker !== null) throw new Error('cluster primary shape');
const w = cluster.fork({ QUENCH_FIXTURE: '1' });
if (w.id !== 1 || !cluster.workers[1] || typeof w.disconnect !== 'function') throw new Error('cluster worker handle');
w.disconnect();
if (!w.exitedAfterDisconnect || w.isConnected()) throw new Error('cluster disconnect state');
const d = domain.create();
let seen = false;
d.on('error', () => { seen = true; });
if (domain.active !== null) throw new Error('domain initial active');
d.run(() => { if (domain.active !== d) throw new Error('domain enter'); });
if (domain.active !== null) throw new Error('domain exit');
d.run(() => { throw new Error('routed'); });
if (!seen) throw new Error('domain error routing');
const roundTrip = v8.deserialize(v8.serialize({ answer: 42 }));
if (roundTrip.answer !== 42) throw new Error('v8 serialization');
if (typeof v8.getHeapStatistics().used_heap_size !== 'number') throw new Error('v8 stats');
console.log('cluster-domain-v8: ok');
