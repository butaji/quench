// Usage: node prismjs-grammars-gen.js <output.h> [jetstream-root]
// Generates prismjs-grammars.h from the grammar object graph of the Prism bundle that
// the JetStream row runs (dist/bundle.es6.min.js). Regex sources and the object graph are
// copied verbatim; ids are assigned by graph walk order.
const fs = require('fs'), vm = require('vm');
const JS = (process.argv[3] || '../jetstream') + '/prismjs';
const bundle = fs.readFileSync(JS + '/dist/bundle.es6.min.js', 'utf8');
const ctx = { console, self: {} }; ctx.globalThis = ctx; ctx.self = ctx;
vm.createContext(ctx);
vm.runInContext(bundle, ctx);
const P = ctx.Prism;
const isRe = (v) => Object.prototype.toString.call(v) === '[object RegExp]';
const gids = new Map(); const grammars = [];
function gid(g) {
  if (gids.has(g)) return gids.get(g);
  const id = grammars.length; gids.set(g, id); grammars.push({ g, id, ents: null }); return id;
}
const pats = []; const patIndex = new Map();
// Pattern descriptor: regex shorthand, or pattern object. Returns pattern id.
function patId(v) {
  const isObj = !isRe(v);
  const re = isObj ? v.pattern : v;
  const lb = isObj && !!v.lookbehind, gr = isObj && !!v.greedy;
  const inside = isObj && v.inside ? gid(v.inside) : -1;
  let alias = isObj && v.alias !== undefined ? v.alias : undefined;
  const aliases = alias === undefined ? [] : (Array.isArray(alias) ? alias : [alias]);
  const d = { src: re.source, flags: re.flags, lb: lb ? 1 : 0, gr: gr ? 1 : 0, inside, aliases };
  pats.push(d); return pats.length - 1;
}
// Walk all grammars reachable from the languages.
const langNames = Object.keys(P.languages).filter((k) => typeof P.languages[k] === 'object' && !Array.isArray(P.languages[k]));
for (const n of langNames) gid(P.languages[n]);
for (let qi = 0; qi < grammars.length; qi++) {
  const G = grammars[qi];
  const ents = [];
  for (const key of Object.keys(G.g)) {
    const v = G.g[key];
    if (!v) continue;
    if (key === 'rest') { ents.push({ key, rest: gid(v), pats: [] }); continue; }
    const list = Array.isArray(v) ? v : [v];
    ents.push({ key, rest: -1, pats: list.map(patId) });
  }
  G.ents = ents;
}
// Emit C.
let out = '/* Generated by the benchmark generator from prismjs/dist/bundle.es6.min.js:\n *   regex sources, flags, lookbehind/greedy/alias flags and the grammar object graph,\n *   in the key order of the final Prism.languages objects. Do not edit by hand. */\n';
const cs = (s) => '"' + s.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\?/g, '\\?').replace(/[^\x20-\x7e]/g, (c) => '\\' + c.charCodeAt(0).toString(8).padStart(3, '0')) + '"';
out += 'typedef struct { const char *src, *flags; int lookbehind, greedy, inside; int naliases; const char *aliases[2]; } PatDesc;\n';
out += 'typedef struct { const char *key; int rest; int npats; int first; } EntDesc;\n';
out += 'typedef struct { int nents; int first; } GramDesc;\n';
out += 'static const PatDesc PATS[] = {\n';
for (const p of pats) out += `  {${cs(p.src)}, ${cs(p.flags)}, ${p.lb}, ${p.gr}, ${p.inside}, ${p.aliases.length}, {${p.aliases.map(cs).join(', ') || '0'}}},\n`;
out += '};\n';
const entFlat = []; const patFlat = [];
let entCount = 0;
const gramLines = [];
for (const G of grammars) {
  gramLines.push(`  {${G.ents.length}, ${entCount}},`);
  for (const e of G.ents) { entFlat.push(`  {${cs(e.key)}, ${e.rest}, ${e.pats.length}, ${patFlat.length}},`); for (const p of e.pats) patFlat.push(p); entCount++; }
}
out += `static const EntDesc ENTS[] = {\n${entFlat.join('\n')}\n};\n`;
out += `static const int ENT_PATS[] = {${patFlat.length ? patFlat.join(', ') : '0'}};\n`;
out += `static const GramDesc GRAMS[] = {\n${gramLines.join('\n')}\n};\n`;
out += `#define N_GRAMS ${grammars.length}\n`;
out += `static const struct { const char *name; int gid; } LANGS[] = {\n${langNames.map((n) => `  {${cs(n)}, ${gids.get(P.languages[n])}},`).join('\n')}\n};\n`;
out += `#define N_LANGS ${langNames.length}\n`;
fs.writeFileSync(process.argv[2], out);
console.log('grammars', grammars.length, 'entries', entCount, 'patterns', pats.length, 'langs', langNames.length);
