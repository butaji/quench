#!/usr/bin/env node
'use strict';
// Node-side reference for the native analogue mandreel-native.cc: runs JetStream's Octane/mandreel.js
// under node and records, after each of the 20 frames of the benchmark's run, the work the native
// driver checks: the rigid-body count, the overlapping pairs, the persistent manifolds and contact
// points (from the broadphase and dispatcher the JS holds), the sum of the body heights, and the
// origin of every body after the last frame.
//
// usage: node tools/mandreel-native-validate.cjs [--jetstream DIR] [--write support/mandreel-native-expected.h]
//
// The JS is not edited on disk: the hooks are inserted into its text in memory. Each hook is placed
// at the first line of a function, and the script checks that each header occurs exactly once.
const fs = require('fs');
const path = require('path');
const vm = require('vm');

function arg(name, fallback) {
  const i = process.argv.indexOf(name);
  return i >= 0 ? process.argv[i + 1] : fallback;
}
const jetstream = arg('--jetstream', path.join(__dirname, '..', '..', 'jetstream'));
const writePath = arg('--write', null);
const src = fs.readFileSync(path.join(jetstream, 'Octane', 'mandreel.js'), 'utf8');

function hook(text, header, code) {
  const marker = header + '\n{';
  const count = text.split(marker).length - 1;
  if (count !== 1) throw new Error(`${header}: found ${count} times`);
  return text.replace(marker, marker + '\n' + code);
}

let text = src;
text = hook(text, 'function _ZN13BenchmarkDemo11initPhysicsEv(sp)', '__mnPhysics.init();');
text = hook(text, 'function _ZN23btDiscreteDynamicsWorld12addRigidBodyEP11btRigidBody(sp)', '__mnPhysics.body(sp);');
text = hook(text, 'function _ZN13BenchmarkDemo20clientMoveAndDisplayEv(sp)', '__mnPhysics.frame(sp);');
if (text.split('function Mandreel_checkState() {\n').length !== 2) throw new Error('Mandreel_checkState');
text = text.replace('function Mandreel_checkState() {\n', 'function Mandreel_checkState() {\n__mnPhysics.frame(-1);\n');
text = hook(
  text,
  'function _ZN21btCollisionDispatcher25dispatchAllCollisionPairsEP22btOverlappingPairCacheRK16btDispatcherInfoP12btDispatcher(sp)',
  '__mnPhysics.dispatcher(sp);'
);

// Per-frame records of the run that runMandreel makes (the second world: the load builds one too).
const state = { recording: false, bodies: [], dispatcher: 0, pairCache: 0, frames: [] };
globalThis.__mnPhysics = {
  init() {
    state.bodies = [];
    state.dispatcher = 0;
    state.pairCache = 0;
    state.frames = [];
    state.recording = true;
  },
  body(sp) {
    state.bodies.push(heap32[(sp >> 2) + 1]);
  },
  dispatcher(sp) {
    if (!state.dispatcher) {
      state.dispatcher = heap32[sp >> 2];
      state.pairCache = heap32[(sp >> 2) + 1];
    }
  },
  frame(sp) {
    if (!state.recording) return;
    // Called before each frame's step (sp is the frame's stack pointer), and once after the last one
    // (sp is -1). Before the first step the dispatcher is not known yet and there are no pairs or manifolds.
    const scratch = sp === -1 ? g_stack_pointer + 800 * 1024 - 64 : sp - 64;
    const call = (fn, self) => {
      heap32[scratch >> 2] = self;
      fn(scratch);
      return r_g0;
    };
    const bodies = state.bodies.length;
    const pairs = state.dispatcher ? call(_ZNK28btHashedOverlappingPairCache22getNumOverlappingPairsEv, state.pairCache) : 0;
    const manifolds = state.dispatcher ? call(_ZNK21btCollisionDispatcher15getNumManifoldsEv, state.dispatcher) : 0;
    let contacts = 0;
    for (let i = 0; i < manifolds; i++) {
      heap32[scratch >> 2] = state.dispatcher;
      heap32[(scratch >> 2) + 1] = i;
      _ZN21btCollisionDispatcher26getManifoldByIndexInternalEi(scratch);
      contacts += heap32[(r_g0 >> 2) + 279];
    }
    let heights = 0;
    const origins = [];
    for (const b of state.bodies) {
      const w = (b >> 2) + 13;
      origins.push(heapFloat[w], heapFloat[w + 1], heapFloat[w + 2]);
      heights += heapFloat[w + 1];
    }
    state.frames.push({ bodies, pairs, manifolds, contacts, heights, origins });
  },
};
globalThis.print = () => {};

vm.runInThisContext(text, { filename: 'mandreel.js' });
// The run to record: runMandreel after the load's own world.
state.recording = false;
runMandreel();
// state.frames[k] is the state after k steps (k = 0 before the first step, 20 after the last).
if (state.frames.length !== 21) throw new Error(`expected 21 states, recorded ${state.frames.length}`);
const frames = state.frames.slice(1);  // frames[f - 1] is the state after step f, as the driver checks it
const bodies = frames[0].bodies;
for (const f of state.frames) {
  if (f.bodies !== bodies) throw new Error('the body count changes between frames');
}

const lines = [];
const list = (values, format) => values.map(format).join(', ');
lines.push('/* Generated by quench-bench/c-analogues/tools/mandreel-native-validate.cjs from node\'s run of');
lines.push(' * JetStream Octane/mandreel.js (the iteration after the load). Each array has one entry per frame,');
lines.push(' * the state after that frame\'s stepSimulation. Regenerate after any change to the benchmark. */');
lines.push('#define kExpectBodies ' + bodies);
lines.push('static const int kExpectPairs[20] = {' + list(frames, (f) => f.pairs) + '};');
lines.push('static const int kExpectManifolds[20] = {' + list(frames, (f) => f.manifolds) + '};');
lines.push('static const int kExpectContacts[20] = {' + list(frames, (f) => f.contacts) + '};');
lines.push('static const double kExpectHeightSum[20] = {' + list(frames, (f) => f.heights.toPrecision(17)) + '};');
const last = frames[19].origins;
lines.push('/* The origins of the bodies after the last frame, body by body (ground box first), x y z. */');
lines.push('static const float kExpectFinal[' + last.length + '] = {');
for (let i = 0; i < last.length; i += 12) {
  lines.push('  ' + last.slice(i, i + 12).map((v) => v.toPrecision(9)).join(', ') + ',');
}
lines.push('};');
const text2 = lines.join('\n') + '\n';

const summary = {
  bodies,
  pairs: frames.map((f) => f.pairs),
  manifolds: frames.map((f) => f.manifolds),
  contacts: frames.map((f) => f.contacts),
  height0: state.frames[0].heights,
  heightLast: frames[19].heights,
};
console.log(JSON.stringify(summary));
if (writePath) {
  fs.writeFileSync(writePath, text2);
  console.log('wrote ' + writePath);
}
