#!/usr/bin/env python3
"""Generate support/ts-enums.h from TypeScript 5.9.2's typescript.js (SyntaxKind and the flag enums).

usage: ts-gen-enums.py <typescript/lib/typescript.js> <out.h>
Values are copied from the bundle so the C parser uses the same numbers as TypeScript.
"""
import re
import sys

src = open(sys.argv[1], encoding="utf8").read().split("\n")


def enum_block(var_name, prefix=None):
    """Return (name, value) pairs of a `var X = ((X5) => { X5[X5["Name"] = n] = "Name"; ... })` enum."""
    start = next(i for i, l in enumerate(src) if l.startswith(f"var {var_name} = "))
    out = []
    if prefix is None:
        prefix = re.search(r"\(\((\w+)\) =>", src[start]).group(1)
    pat = re.compile(r'\b' + re.escape(prefix) + r'\["(\w+)"\] = (-?\d+)\] = "(\w+)"')
    pat_expr = re.compile(r'\b' + re.escape(prefix) + r'\["(\w+)"\] = ([^\]]+)\] = "(\w+)"')
    for line in src[start + 1:]:
        if line.startswith("})("):
            break
        m = pat.search(line)
        if m and m.group(1) == m.group(3):
            out.append((m.group(1), int(m.group(2))))
            continue
        m = pat_expr.search(line)
        if m and m.group(1) == m.group(3):
            expr = m.group(2).split("/*")[0].strip()
            if re.fullmatch(r"-?\d+", expr):
                out.append((m.group(1), int(expr)))
            elif re.fullmatch(r"[\s\d|()<>~]+", expr) or re.fullmatch(r"\w+\s*(\|\s*\w+)*", expr) is None:
                pass
    return out


def emit(f, name, pairs, cprefix):
    f.write(f"enum {{ /* {name} */\n")
    for n, v in pairs:
        f.write(f"  {cprefix}{n} = {v},\n")
    f.write("};\n\n")


with open(sys.argv[2], "w", encoding="utf8") as f:
    f.write("/* Generated by tools/ts-gen-enums.py from TypeScript 5.9.2 typescript.js. Do not edit. */\n")
    f.write("#ifndef TS_ENUMS_H\n#define TS_ENUMS_H\n\n")
    kinds = enum_block("SyntaxKind", "SyntaxKind5")
    emit(f, "SyntaxKind", kinds, "TSK_")
    for var, cp in [("NodeFlags", "TNF_"), ("ModifierFlags", "TMF_"), ("TransformFlags", "TTF_")]:
        emit(f, var, enum_block(var), cp)
    f.write("#endif\n")
    print("kinds", len(kinds))
