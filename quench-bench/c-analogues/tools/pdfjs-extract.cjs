// Generates the data tables used by quench-bench/c-analogues/pdfjs.c from the
// JetStream sources: the embedded PDF (decoded from getPDF()'s base64 once at
// setup in JS, so the C embeds the bytes) and the constant tables of pdfjs.js.
// usage: node pdfjs-extract.cjs [JETSTREAM_ROOT] [OUT_DIR]
'use strict';
const fs = require('fs');
const path = require('path');
const root = process.argv[2] || path.join(__dirname, '../../../../../quench/quench-bench/jetstream');
const outDir = process.argv[3] || path.join(__dirname, '../support');
const src = fs.readFileSync(path.join(root, 'Octane/pdfjs.js'), 'utf8');

// Slice a top-level "var NAME = [...]" / "{...}" literal and evaluate it.
function lit(name) {
  const m = new RegExp('var ' + name + ' = ([\\[{])').exec(src);
  if (!m) throw new Error('table not found: ' + name);
  const start = m.index + m[0].length - 1;
  let depth = 0, j = start;
  for (; ; j++) {
    const c = src[j];
    if (c === '[' || c === '{') depth++;
    else if (c === ']' || c === '}') { if (--depth === 0) break; }
  }
  return new Function('return ' + src.slice(start, j + 1))();
}
const cstr = (s) => '"' + s.replace(/\\/g, '\\\\').replace(/"/g, '\\"') + '"';

// 1. The PDF: getPDF() returns the base64 text of the document.
const pdfLine = src.split('\n').find((l) => /^\s*return "[A-Za-z0-9+\/=]+";?$/.test(l));
const pdf = Buffer.from(pdfLine.slice(pdfLine.indexOf('"') + 1, pdfLine.lastIndexOf('"')), 'base64');
let out = '/* Generated by tools/pdfjs-extract.cjs from Octane/pdfjs.js (getPDF()). Do not edit. */\n';
out += '#define PDFJS_PDF_LEN ' + pdf.length + '\n';
out += 'static const unsigned char pdfjs_pdf[PDFJS_PDF_LEN] = {\n';
for (let i = 0; i < pdf.length; i += 20) {
  out += '  ' + Array.from(pdf.subarray(i, i + 20)).join(',') + ',\n';
}
out += '};\n';
fs.writeFileSync(path.join(outDir, 'pdfjs-data.h'), out);

// 2. Constant tables.
const GU = lit('GlyphsUnicode');
const names = Object.keys(GU);
let t = '/* Generated by tools/pdfjs-extract.cjs from Octane/pdfjs.js. Do not edit. */\n';
t += '/* GlyphsUnicode: glyph name -> unicode (JS object literal, insertion order). */\n';
t += 'static const struct { const char *name; int code; } pdfjs_glyphs_unicode[] = {\n';
for (const k of names) t += '  {' + cstr(k) + ',' + GU[k] + '},\n';
t += '};\n#define PDFJS_GLYPHS_UNICODE_LEN ' + names.length + '\n\n';

const E = lit('Encodings');
for (const k of Object.keys(E)) {
  t += 'static const char *const pdfjs_enc_' + k + '[] = {\n';
  t += E[k].map((s) => '  ' + cstr(s) + ',\n').join('');
  t += '};\n#define PDFJS_ENC_' + k + '_LEN ' + E[k].length + '\n';
}
t += '\n';

const CFS = lit('CFFStandardStrings');
t += 'static const char *const pdfjs_cff_standard_strings[] = {\n';
t += CFS.map((s) => '  ' + cstr(s) + ',\n').join('') + '};\n';
t += '#define PDFJS_CFF_STANDARD_STRINGS_LEN ' + CFS.length + '\n\n';

const PST = lit('PDFStringTranslateTable');
t += '/* PDFStringTranslateTable (holes are 0, which JS treats as falsy). */\n';
t += 'static const unsigned short pdfjs_pdfstring_translate[] = {\n';
for (let i = 0; i < PST.length; i += 12) {
  t += '  ' + Array.from({ length: Math.min(12, PST.length - i) }, (_, k) => PST[i + k] || 0).join(',') + ',\n';
}
t += '};\n#define PDFJS_PDFSTRING_TRANSLATE_LEN ' + PST.length + '\n\n';

const UR = lit('UnicodeRanges');
t += 'static const struct { int begin, end; } pdfjs_unicode_ranges[] = {\n';
t += UR.map((r) => '  {' + r.begin + ',' + r.end + '},\n').join('') + '};\n';
t += '#define PDFJS_UNICODE_RANGES_LEN ' + UR.length + '\n';
fs.writeFileSync(path.join(outDir, 'pdfjs-tables.h'), t);
console.log('pdf bytes', pdf.length, 'glyph names', names.length, 'cff strings', CFS.length);
