#!/usr/bin/env python3
"""Generate support/ts-protos.h for the TypeScript parser port.

 - prototypes for every top-level `static ... name(...)` definition in ts-scanner.h, ts-parser.h
   and ts-jsdoc.h (single-line or multi-line), so the port can call forward as the JS does;
 - callback thunks `static intptr_t cb_NAME(void)` for every `cb_NAME` the parser passes as a
   TsCb, when the thunk is not defined in the parser by hand: `cb_NAME` calls `NAME()`;
   names in CUSTOM need a specific argument list and are defined by hand in CUSTOM_BODIES.
"""
import re
import sys
from pathlib import Path

CUSTOM_BODIES = {
    # name: C body (returns intptr_t)
    'parseAssignmentExpressionTrue': '{ return (intptr_t)parseAssignmentExpressionOrHigher(true); }',
    'parseAssignmentExpressionFalse': '{ return (intptr_t)parseAssignmentExpressionOrHigher(false); }',
    'parseAssignmentExpressionFalseDisallowIn': '{ return (intptr_t)parseAssignmentExpressionOrHigher(false); }',
    'parseEnumMemberList': '{ return (intptr_t)parseDelimitedList(PC_EnumMembers, parseEnumMember, false); }',
}

def definitions(text):
    lines = text.splitlines()
    i = 0
    while i < len(lines):
        line = lines[i]
        i += 1
        if not line.startswith('static ') or '(' not in line:
            continue
        # a definition may continue over several lines until its opening brace
        head = line
        j = i
        while '{' not in head and ';' not in head and j < len(lines):
            head = head + ' ' + lines[j].strip()
            j += 1
        if ';' in head.split('{')[0] and '{' not in head:
            continue
        head = head.split('{', 1)[0].rstrip()
        if head.endswith(';'):
            continue
        if '=' in head.split('(', 1)[0]:
            continue
        if head.startswith(('static const', 'static struct', 'static enum', 'static inline')):
            continue
        yield head

def emit(out_name, guard, srcs, support):
    text = ''.join(p.read_text() for p in srcs)
    heads = list(definitions(text))
    defined_names = set()
    lines = ['/* Generated by tools/ts-gen-protos.py. Do not edit. */', f'#ifndef {guard}', f'#define {guard}']
    for h in heads:
        name = re.search(r'(\w+)\(', h).group(1)
        defined_names.add(name)
        lines.append(h + ';')
    used = sorted(set(re.findall(r'\bcb_(\w+)', text)))
    thunks = []
    for n in used:
        cb = 'cb_' + n
        if re.search(r'static intptr_t ' + cb + r'\(void\)', text):
            continue
        if n in CUSTOM_BODIES:
            body = CUSTOM_BODIES[n]
        elif n in defined_names:
            body = f'{{ return (intptr_t){n}(); }}'
        else:
            lines.append(f'/* MISSING {cb} */')
            continue
        lines.append(f'static intptr_t {cb}(void);')
        thunks.append(f'static intptr_t {cb}(void) {body}')
    out = '\n'.join(lines) + '\n' + '\n'.join(thunks) + '\n#endif\n'
    (support / out_name).write_text(out)
    print(out_name, 'prototypes:', len(heads), 'thunks generated:', len(thunks))

def main():
    support = Path(sys.argv[1])
    core = [support / n for n in ('ts-scanner.h', 'ts-parser.h') if (support / n).exists()]
    emit('ts-protos.h', 'TS_PROTOS_H', core, support)
    emit('ts-jsdoc-protos.h', 'TS_JSDOC_PROTOS_H', [support / 'ts-jsdoc.h'], support)

if __name__ == '__main__':
    main()
