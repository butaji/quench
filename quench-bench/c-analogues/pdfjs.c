/* Charstring items: JS arrays mix numbers and command names. */
enum { CMD_NONE = 0, CMD_NEG1 = -1 };
enum {
  C_HSTEM = 1, C_VSTEM, C_VMOVETO, C_RLINETO, C_HLINETO, C_VLINETO, C_RRCURVETO,
  C_CALLSUBR, C_RETURN, C_SUB, C_DIV, C_EXCH, C_FLEX, C_DROP, C_ENDCHAR, C_RMOVETO,
  C_HMOVETO, C_VHCURVETO, C_HVCURVETO, C_CALLOTHERSUBR, C_POP
};

typedef struct { uint8_t isstr; int cmd; double num; } CsItem;
typedef struct { CsItem *a; int n, cap; } Cs;

static void cs_push(Cs *c, CsItem it) {
  if (c->n == c->cap) {
    int nc = c->cap ? c->cap * 2 : 16;
    CsItem *na = aalloc(sizeof(CsItem) * (size_t)nc);
    if (c->n) memcpy(na, c->a, sizeof(CsItem) * (size_t)c->n);
    c->a = na;
    c->cap = nc;
  }
  c->a[c->n++] = it;
}
static CsItem cs_num(double v) {
  CsItem it;
  memset(&it, 0, sizeof it);
  it.num = v;
  return it;
}
static CsItem cs_cmd(int cmd) {
  CsItem it;
  memset(&it, 0, sizeof it);
  it.isstr = 1;
  it.cmd = cmd;
  return it;
}
static double cs_numval(CsItem it) { return it.isstr ? NAN : it.num; }
static CsItem cs_pop(Cs *c) {
  if (c->n == 0) {
    CsItem u;
    memset(&u, 0, sizeof u);
    u.num = NAN;
    return u;
  }
  return c->a[--c->n];
}

static int cs_dict1(int v) {
  switch (v) {
  case 1: return C_HSTEM;
  case 3: return C_VSTEM;
  case 4: return C_VMOVETO;
  case 5: return C_RLINETO;
  case 6: return C_HLINETO;
  case 7: return C_VLINETO;
  case 8: return C_RRCURVETO;
  case 10: return C_CALLSUBR;
  case 11: return C_RETURN;
  case 14: return C_ENDCHAR;
  case 21: return C_RMOVETO;
  case 22: return C_HMOVETO;
  case 30: return C_VHCURVETO;
  case 31: return C_HVCURVETO;
  default: return CMD_NONE;   /* 9 closepath, 13 hsbw (handled earlier), undefined */
  }
}
static int cs_dict12(int v) {
  switch (v) {
  case 1: return C_VSTEM;
  case 2: return C_HSTEM;
  case 6: return CMD_NEG1;   /* seac */
  case 7: return CMD_NEG1;   /* sbw */
  case 11: return C_SUB;
  case 12: return C_DIV;
  case 16: return C_CALLOTHERSUBR;
  case 17: return C_POP;
  default: return CMD_NONE;  /* dotsection, setcurrentpoint, undefined */
  }
}

/* parseFloat(s): longest decimal prefix; NaN when there is none. */
static double parse_float_tok(Bytes b) {
  int i = 0;
  while (i < b.n && (b.p[i] == ' ' || b.p[i] == '\t' || b.p[i] == '\n' || b.p[i] == '\r')) i++;
  int st = i;
  if (i < b.n && (b.p[i] == '+' || b.p[i] == '-')) i++;
  if (b.n - i >= 8 && memcmp(b.p + i, "Infinity", 8) == 0) return b.p[st] == '-' ? -INFINITY : INFINITY;
  int digits = 0;
  while (i < b.n && b.p[i] >= '0' && b.p[i] <= '9') { i++; digits++; }
  if (i < b.n && b.p[i] == '.') {
    i++;
    while (i < b.n && b.p[i] >= '0' && b.p[i] <= '9') { i++; digits++; }
  }
  if (digits == 0) return NAN;
  int end = i;
  if (i < b.n && (b.p[i] == 'e' || b.p[i] == 'E')) {
    int j = i + 1;
    if (j < b.n && (b.p[j] == '+' || b.p[j] == '-')) j++;
    if (j < b.n && b.p[j] >= '0' && b.p[j] <= '9') {
      while (j < b.n && b.p[j] >= '0' && b.p[j] <= '9') j++;
      end = j;
    }
  }
  char tmp[128];
  int n = end - st < 127 ? end - st : 127;
  memcpy(tmp, b.p + st, (size_t)n);
  tmp[n] = 0;
  return strtod(tmp, NULL);
}

/* parseInt(s, 10): optional whitespace and sign, then digits; NaN if none. */
static double js_parseint(Bytes b) {
  int i = 0;
  while (i < b.n && (b.p[i] == ' ' || b.p[i] == '\t' || b.p[i] == '\n' || b.p[i] == '\r')) i++;
  int neg = 0;
  if (i < b.n && (b.p[i] == '+' || b.p[i] == '-')) {
    neg = b.p[i] == '-';
    i++;
  }
  if (!(i < b.n && b.p[i] >= '0' && b.p[i] <= '9')) return NAN;
  double v = 0;
  while (i < b.n && b.p[i] >= '0' && b.p[i] <= '9') v = v * 10 + (b.p[i++] - '0');
  return neg ? -v : v;
}

static int g_hinting_enabled = 0;   /* kHintingEnabled is false in this build */
static long long g_count_decode;    /* decodeCharString calls (validation counter) */

typedef struct { Cs cs; double lsb, width; } Decoded;

static int at_byte(const uint8_t *a, int count, int i) {
  if (i < 0 || i >= count) die("truncated charstring or font program");
  return a[i];
}
static int cs_is_cmd(CsItem it, int cmd) { return it.isstr && it.cmd == cmd; }
static void cs_remove_front(Cs *cs, int k) {
  memmove(cs->a, cs->a + k, sizeof(CsItem) * (size_t)(cs->n - k));
  cs->n -= k;
}

/* Type1Parser.decodeCharString (charStringDictionary, hinting disabled). */
static Decoded decode_charstring(const uint8_t *array, int count) {
  Decoded out;
  g_count_decode++;
  memset(&out, 0, sizeof out);
  Cs cs = {0};
  double lsb = 0, width = 0;
  int flexState = 0;
  for (int i = 0; i < count; i++) {
    int value = array[i];
    if (value < 32) {
      int command = CMD_NONE;
      int escape = -1;
      if (value == 12) {
        escape = ++i < count ? array[i] : -1;
        if (escape == 16) {
          CsItem index = cs_pop(&cs);
          CsItem argc = cs_pop(&cs);
          double ac = cs_numval(argc);
          for (int j = 0; j < ac; j++) cs_push(&cs, cs_cmd(C_DROP));
          double ix = cs_numval(index);
          if (ix < 3) continue;
          if (ix == 3) {
            cs_push(&cs, cs_num(3));
            i++;
            continue;
          }
          command = cs_dict12(escape);
        } else if (escape == 17 || escape == 33) {
          continue;
        } else if (!g_hinting_enabled && (escape == 1 || escape == 2)) {
          for (int k = 0; k < 6; k++) cs_push(&cs, cs_cmd(C_DROP));
          continue;
        } else {
          command = cs_dict12(escape);
        }
      } else if (value == 13) { /* hsbw */
        if (cs.n == 2) {
          lsb = cs_numval(cs.a[0]);
          width = cs_numval(cs.a[1]);
          cs_remove_front(&cs, 1);
        } else if (cs.n == 4 && cs_is_cmd(cs.a[3], C_DIV)) {
          lsb = cs_numval(cs.a[0]);
          width = cs_numval(cs.a[1]) / cs_numval(cs.a[2]);
          cs_remove_front(&cs, 1);
        } else if (cs.n == 4 && cs_is_cmd(cs.a[2], C_DIV)) {
          lsb = cs_numval(cs.a[0]) / cs_numval(cs.a[1]);
          width = cs_numval(cs.a[3]);
          cs_remove_front(&cs, 3);
        } else {
          die("Unsupported hsbw format");
        }
        cs_push(&cs, cs_num(lsb));
        cs_push(&cs, cs_cmd(C_HMOVETO));
        continue;
      } else if (value == 10) { /* callsubr */
        if (cs.n > 0 && !cs.a[cs.n - 1].isstr && cs.a[cs.n - 1].num < 3) {
          CsItem sn = cs_pop(&cs);
          if (!sn.isstr) {
            if (sn.num == 1) {
              flexState = 1;
            } else if (sn.num == 2) {
              flexState = 2;
            } else if (sn.num == 0) {
              cs_push(&cs, cs_cmd(C_EXCH));
              cs_push(&cs, cs_cmd(C_DROP));
              cs_push(&cs, cs_cmd(C_EXCH));
              cs_push(&cs, cs_cmd(C_DROP));
              cs_push(&cs, cs_cmd(C_FLEX));
              flexState = 0;
            }
          }
          continue;
        }
        command = cs_dict1(10);
      } else if (value == 21 && flexState > 0) {
        if (flexState > 1) continue;   /* ignoring rmoveto */
        value = 5;                     /* first segment replaced by rlineto */
        command = cs_dict1(5);
      } else if (!g_hinting_enabled && (value == 1 || value == 3)) {
        cs_push(&cs, cs_cmd(C_DROP));
        cs_push(&cs, cs_cmd(C_DROP));
        continue;
      } else {
        command = cs_dict1(value);
      }
      if (command == CMD_NONE && i < count) continue;
      if (command == CMD_NONE) break;
      if (command == CMD_NEG1) {
        if (value == 12 && escape == 7) {
          for (int k = 0; k < 4; k++) cs_push(&cs, cs_cmd(C_DROP));
          continue;
        }
        if (value == 12 && escape == 8) {
          cs_push(&cs, cs_cmd(C_DROP));
          continue;
        }
        cs_push(&cs, cs_num(-1));
      } else {
        cs_push(&cs, cs_cmd(command));
      }
    } else if (value <= 246) {
      cs_push(&cs, cs_num(value - 139));
    } else if (value <= 250) {
      int w = at_byte(array, count, ++i);
      cs_push(&cs, cs_num(((value - 247) * 256) + w + 108));
    } else if (value <= 254) {
      int w = at_byte(array, count, ++i);
      cs_push(&cs, cs_num(-((value - 251) * 256) - w - 108));
    } else {
      int b0 = at_byte(array, count, ++i), b1 = at_byte(array, count, ++i);
      int b2 = at_byte(array, count, ++i), b3 = at_byte(array, count, ++i);
      uint32_t v = ((uint32_t)(b0 & 0xff) << 24) | ((uint32_t)(b1 & 0xff) << 16) |
                   ((uint32_t)(b2 & 0xff) << 8) | ((uint32_t)(b3 & 0xff));
      cs_push(&cs, cs_num((double)(int32_t)v));
    }
  }
  out.cs = cs;
  out.lsb = lsb;
  out.width = width;
  return out;
}

/* Byte slice with JS slice(start, end) clamping; end may be NaN (-> 0). */
static Bytes slice_bytes(Bytes b, double start, double end) {
  double s = start != start ? 0 : start;
  double e = end != end ? 0 : end;
  if (s < 0) s = s + b.n < 0 ? 0 : s + b.n;
  if (e < 0) e = e + b.n < 0 ? 0 : e + b.n;
  if (s > b.n) s = b.n;
  if (e > b.n) e = b.n;
  Bytes r = {b.p + (int)s, e > s ? (int)(e - s) : 0};
  return r;
}

/* decrypt(stream, key, discardNumber). */
static Bytes t1_decrypt(Bytes stream, int key, double discard) {
  uint8_t *out = aalloc((size_t)stream.n + 1);
  uint32_t r = (uint32_t)key;
  for (int i = 0; i < stream.n; i++) {
    uint32_t value = stream.p[i];
    out[i] = (uint8_t)(value ^ (r >> 8));
    r = ((value + r) * 52845u + 22719u) & 0xffff;
  }
  Bytes whole = {out, stream.n};
  return slice_bytes(whole, discard, (double)stream.n);
}

/* Type1Font.commandsMap; returns 1 (single number), 2 (pair) or 0 (absent). */
static int cs_map(int cmd, int *a, int *b) {
  switch (cmd) {
  case C_HSTEM: *a = 1; return 1;
  case C_VSTEM: *a = 3; return 1;
  case C_VMOVETO: *a = 4; return 1;
  case C_RLINETO: *a = 5; return 1;
  case C_HLINETO: *a = 6; return 1;
  case C_VLINETO: *a = 7; return 1;
  case C_RRCURVETO: *a = 8; return 1;
  case C_CALLSUBR: *a = 10; return 1;
  case C_RETURN: *a = 11; return 1;
  case C_SUB: *a = 12; *b = 11; return 2;
  case C_DIV: *a = 12; *b = 12; return 2;
  case C_EXCH: *a = 12; *b = 28; return 2;
  case C_FLEX: *a = 12; *b = 35; return 2;
  case C_DROP: *a = 12; *b = 18; return 2;
  case C_ENDCHAR: *a = 14; return 1;
  case C_RMOVETO: *a = 21; return 1;
  case C_HMOVETO: *a = 22; return 1;
  case C_VHCURVETO: *a = 30; return 1;
  case C_HVCURVETO: *a = 31; return 1;
  default: return 0;
  }
}

/* Type1Font.flattenCharstring: every number becomes 28 hi lo; commands become
 * their Type 2 operators. Works on the original items: the JS splice edits
 * only positions it has already passed (and the divisor it reads at i+1). */
static Bytes flatten_charstring(const Cs *cs) {
  uint8_t *out = aalloc((size_t)cs->n * 3 + 4);
  int o = 0;
  for (int k = 0; k < cs->n;) {
    CsItem it = cs->a[k];
    if (it.isstr) {
      int a = 0, b = 0;
      int kind = cs_map(it.cmd, &a, &b);
      if (!kind) die("Unknow command in charstring");
      out[o++] = (uint8_t)a;
      if (kind == 2) out[o++] = (uint8_t)b;
      k++;
    } else {
      double c = it.num;
      if (c > 32000) {
        double divisor = k + 1 < cs->n ? cs_numval(cs->a[k + 1]) : NAN;
        c /= divisor;
        int32_t iv = js_i32(c);
        out[o++] = 28;
        out[o++] = (uint8_t)((iv >> 8) & 0xff);
        out[o++] = (uint8_t)(iv & 0xff);
        k += 3;
      } else {
        int32_t iv = js_i32(c);
        out[o++] = 28;
        out[o++] = (uint8_t)((iv >> 8) & 0xff);
        out[o++] = (uint8_t)(iv & 0xff);
        k += 1;
      }
    }
  }
  Bytes r = {out, o};
  return r;
}

/* Private dictionary values the CFF writer reads (properties.privateData). */
enum {
  PD_BLUEVALUES, PD_OTHERBLUES, PD_FAMILYBLUES, PD_FAMILYOTHERBLUES, PD_STEMSNAPH,
  PD_STEMSNAPV, PD_BLUESHIFT, PD_BLUEFUZZ, PD_BLUESCALE, PD_LANGUAGEGROUP,
  PD_EXPANSIONFACTOR, PD_STDHW, PD_STDVW, PD_NUM
};
static const char *const k_pd_names[PD_NUM] = {
  "BlueValues", "OtherBlues", "FamilyBlues", "FamilyOtherBlues", "StemSnapH",
  "StemSnapV", "BlueShift", "BlueFuzz", "BlueScale", "LanguageGroup",
  "ExpansionFactor", "StdHW", "StdVW"};
typedef struct {
  double lenIV;
  uint8_t has[PD_NUM], isarr[PD_NUM];
  double num[PD_NUM];
  double *arr[PD_NUM];
  int arrn[PD_NUM];
} PrivData;

/* readNumberArray(str, index): tokens of the text between '[' and ']'. */
static void read_number_array(const uint8_t *str, int n, int index, double **out, int *outn) {
  int start = index;
  while (index < n && str[index] != '[') { index++; start++; }
  index++;
  start++;
  int count = 0;
  int j = index;
  while (j < n && str[j] != ']') { j++; count++; }
  if (start > n) start = n;
  if (start + count > n) count = n - start;
  /* trim, collapse whitespace runs to ' ', split(' '), parseFloat(x || 0) */
  double *vals = NULL;
  int nt = 0, cap = 0;
  Buf tok = {0};
  int lastSpace = 1;
  int k;   /* the token loop runs one step past the end to flush the last token */
  for (k = 0; k <= count; k++) {
    int c = k < count ? str[start + k] : ' ';
    int isws = c == ' ' || c == '\t' || c == '\n' || c == '\r' || c == '\f' || c == '\v';
    if (isws) {
      if (!lastSpace) {
        if (nt == cap) {
          int nc = cap ? cap * 2 : 8;
          double *nv = aalloc(sizeof(double) * (size_t)nc);
          if (nt) memcpy(nv, vals, sizeof(double) * (size_t)nt);
          vals = nv;
          cap = nc;
        }
        vals[nt++] = parse_float_tok(buf_view(&tok));
        tok.n = 0;
        lastSpace = 1;
      }
    } else {
      buf_c(&tok, c);
      lastSpace = 0;
    }
  }
  if (nt == 0) {                 /* split of '' gives [''] -> parseFloat(0) */
    vals = aalloc(sizeof(double));
    vals[0] = 0;
    nt = 1;
  }
  *out = vals;
  *outn = nt;
}

/* readNumber(str, index) = parseFloat(substr || 0) after skipping spaces. */
static double read_number(const uint8_t *str, int n, int index) {
  while (index < n && str[index] == ' ') index++;
  int start = index;
  int count = 0;
  while (index < n && str[index] != ' ') { index++; count++; }
  if (count == 0) return 0;
  return parse_float_tok((Bytes){str + start, count});
}

static int is_sep(int c) { return c == ' ' || c == '\n' || c == '\r'; }

/* A parsed Type 1 font program (Type1Parser.extractFontProgram). */
typedef struct {
  Bytes glyph;
  Cs charstring;
  double lsb, width;
} T1Glyph;

typedef struct {
  T1Glyph *glyphs;
  int nglyphs, capglyphs;
  Cs *subrs;          /* program.subrs; entries without subrHas are holes */
  uint8_t *subrHas;
  int nsubrs, capsubrs;
  PrivData pd;
} T1Program;

static void t1_set_subr(T1Program *prog, int idx, Cs cs) {
  if (idx >= prog->capsubrs) {
    int nc = prog->capsubrs ? prog->capsubrs : 16;
    while (nc <= idx) nc *= 2;
    Cs *ns = aalloc(sizeof(Cs) * (size_t)nc);
    uint8_t *nh = aalloc((size_t)nc);
    if (prog->capsubrs) {
      memcpy(ns, prog->subrs, sizeof(Cs) * (size_t)prog->capsubrs);
      memcpy(nh, prog->subrHas, (size_t)prog->capsubrs);
    }
    prog->subrs = ns;
    prog->subrHas = nh;
    prog->capsubrs = nc;
  }
  prog->subrs[idx] = cs;
  prog->subrHas[idx] = 1;
  if (idx >= prog->nsubrs) prog->nsubrs = idx + 1;
}

/* Type1Parser.extractFontProgram on the decrypted-by-caller eexec block. */
static T1Program *t1_extract_program(Bytes encrypted) {
  Bytes eexec = t1_decrypt(encrypted, 55665, 4);
  T1Program *prog = aalloc(sizeof(T1Program));
  prog->pd.lenIV = 4;
  int glyphsSection = 0, subrsSection = 0;
  Buf token = {0};
  Buf glyph = {0};
  double length = 0;
  int count = eexec.n;
  const uint8_t *s = eexec.p;
  int i = 0;

  /* getToken() of the JS (closes over i and the eexec text). */
#define GET_TOKEN(out)                                              \
  do {                                                              \
    while (i < count && is_sep(s[i])) ++i;                          \
    int st_ = i;                                                    \
    while (i < count && !is_sep(s[i])) ++i;                         \
    (out) = (Bytes){s + st_, i - st_};                              \
  } while (0)

  for (i = 0; i < count; i++) {
    int c = s[i];
    if ((glyphsSection || subrsSection) &&
        (bytes_eq(buf_view(&token), "RD") || bytes_eq(buf_view(&token), "-|"))) {
      i++;
      Bytes data = slice_bytes(eexec, i, i + length);
      Bytes encoded = t1_decrypt(data, 4330, prog->pd.lenIV);
      Decoded d = decode_charstring(encoded.p, encoded.n);
      if (glyphsSection) {
        if (prog->nglyphs == prog->capglyphs) {
          int nc = prog->capglyphs ? prog->capglyphs * 2 : 64;
          T1Glyph *ng = aalloc(sizeof(T1Glyph) * (size_t)nc);
          if (prog->nglyphs) memcpy(ng, prog->glyphs, sizeof(T1Glyph) * (size_t)prog->nglyphs);
          prog->glyphs = ng;
          prog->capglyphs = nc;
        }
        T1Glyph *g = &prog->glyphs[prog->nglyphs++];
        g->glyph = bytes_copy(glyph.p, glyph.n);
        g->charstring = d.cs;
        g->lsb = d.lsb;
        g->width = d.width;
      } else {
        die("subrs section outside the Private dictionary is not used by this document");
      }
      if (length != length) { i = count; break; }   /* i = NaN ends the JS loop */
      i += (int)length;
      token.n = 0;
    } else if (is_sep(c)) {
      length = js_parseint(buf_view(&token));
      token.n = 0;
    } else {
      buf_c(&token, c);
      if (!glyphsSection) {
        Bytes t = buf_view(&token);
        if (bytes_eq(t, "/CharString")) {
          glyphsSection = 1;
        } else if (bytes_eq(t, "/Subrs")) {
          ++i;
          Bytes tk;
          GET_TOKEN(tk);
          double num = js_parseint(tk);
          GET_TOKEN(tk);   /* 'array' */
          for (int j = 0; j < num; ++j) {
            GET_TOKEN(tk);   /* 'dup' */
            if (bytes_eq(tk, "ND") || bytes_eq(tk, "|-") || bytes_eq(tk, "noaccess")) break;
            GET_TOKEN(tk);
            double index = js_parseint(tk);
            if (index > j) j = (int)index;
            GET_TOKEN(tk);
            length = js_parseint(tk);
            GET_TOKEN(tk);   /* 'RD' */
            Bytes data = slice_bytes(eexec, i + 1, i + 1 + length);
            Bytes encoded = t1_decrypt(data, 4330, prog->pd.lenIV);
            Decoded d = decode_charstring(encoded.p, encoded.n);
            i = (int)(i + 1 + length);
            GET_TOKEN(tk);   /* 'NP' */
            if (bytes_eq(tk, "noaccess")) GET_TOKEN(tk);   /* 'put' */
            if (index < 0 || index > 1 << 20) die("subr index out of range");
            t1_set_subr(prog, (int)index, d.cs);
          }
          /* the JS 'break' leaves the switch; token keeps '/Subrs' */
        } else if (bytes_eq(t, "/BlueValues") || bytes_eq(t, "/OtherBlues") ||
                   bytes_eq(t, "/FamilyBlues") || bytes_eq(t, "/FamilyOtherBlues") ||
                   bytes_eq(t, "/StemSnapH") || bytes_eq(t, "/StemSnapV")) {
          int k = 0;
          for (k = 0; k < PD_NUM; k++)
            if (t.n - 1 == (int)strlen(k_pd_names[k]) && memcmp(t.p + 1, k_pd_names[k], (size_t)t.n - 1) == 0)
              break;
          read_number_array(s, count, i + 1, &prog->pd.arr[k], &prog->pd.arrn[k]);
          prog->pd.isarr[k] = 1;
          prog->pd.has[k] = 1;
        } else if (bytes_eq(t, "/StdHW") || bytes_eq(t, "/StdVW")) {
          int k = bytes_eq(t, "/StdHW") ? PD_STDHW : PD_STDVW;
          double *vv;
          int vn;
          read_number_array(s, count, i + 2, &vv, &vn);
          prog->pd.num[k] = vv[0];
          prog->pd.has[k] = 1;
        } else if (bytes_eq(t, "/BlueShift") || bytes_eq(t, "/lenIV") || bytes_eq(t, "/BlueFuzz") ||
                   bytes_eq(t, "/BlueScale") || bytes_eq(t, "/LanguageGroup") ||
                   bytes_eq(t, "/ExpansionFactor")) {
          double v = read_number(s, count, i + 1);
          if (bytes_eq(t, "/lenIV")) {
            prog->pd.lenIV = v;
          } else {
            int k = 0;
            for (k = 0; k < PD_NUM; k++)
              if (t.n - 1 == (int)strlen(k_pd_names[k]) && memcmp(t.p + 1, k_pd_names[k], (size_t)t.n - 1) == 0)
                break;
            prog->pd.num[k] = v;
            prog->pd.has[k] = 1;
          }
        }
      } else if (c == '/') {
        token.n = 0;
        glyph.n = 0;
        while (i + 1 < count && (c = s[++i]) != ' ') buf_c(&glyph, c);
      }
    }
  }
#undef GET_TOKEN
  return prog;
}

