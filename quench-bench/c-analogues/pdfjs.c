static int tohexdigit(int ch) {
  if (ch >= '0' && ch <= '9') return ch - 48;
  if (ch >= 'a' && ch <= 'f') return ch - 'a' + 10;
  if (ch >= 'A' && ch <= 'F') return ch - 'A' + 10;
  return -1;
}

static Obj lex_getnumber(Lexer *L, int ch) {
  int floating = 0;
  Buf str = {0};
  buf_c(&str, ch);
  Stream *s = L->s;
  for (;;) {
    ch = st_lookchar(s);
    if (ch == '.' && !floating) {
      buf_c(&str, ch);
      floating = 1;
    } else if (ch == '-') {
      /* ignore minus signs in the middle of numbers (Adobe behavior) */
    } else if (ch >= '0' && ch <= '9') {
      buf_c(&str, ch);
    } else if (ch == 'e' || ch == 'E') {
      floating = 1;
    } else {
      break;
    }
    st_skip(s, 1);
  }
  char tmp[64];
  int n = str.n < 63 ? str.n : 63;
  memcpy(tmp, str.p, (size_t)n);
  tmp[n] = 0;
  char *end = NULL;
  double v = strtod(tmp, &end);
  if (end == tmp) die("Invalid floating point number");
  return O_num(v);
}

static Obj lex_getstring(Lexer *L) {
  int numParen = 1, done = 0;
  Buf str = {0};
  Stream *s = L->s;
  int ch;
  do {
    ch = st_getchar(s);
    if (ch < 0) {
      done = 1;
      continue;
    }
    switch (ch) {
    case '(':
      ++numParen;
      buf_c(&str, ch);
      break;
    case ')':
      if (--numParen == 0) done = 1;
      else buf_c(&str, ch);
      break;
    case '\\':
      ch = st_getchar(s);
      if (ch < 0) {
        done = 1;
        break;
      }
      switch (ch) {
      case 'n': buf_c(&str, '\n'); break;
      case 'r': buf_c(&str, '\r'); break;
      case 't': buf_c(&str, '\t'); break;
      case 'b': buf_c(&str, '\b'); break;
      case 'f': buf_c(&str, '\f'); break;
      case '\\': case '(': case ')': buf_c(&str, ch); break;
      case '0': case '1': case '2': case '3':
      case '4': case '5': case '6': case '7': {
        int x = ch - '0';
        ch = st_lookchar(s);
        if (ch >= '0' && ch <= '7') {
          st_skip(s, 1);
          x = (x << 3) + (ch - '0');
          ch = st_lookchar(s);
          if (ch >= '0' && ch <= '7') {
            st_skip(s, 1);
            x = (x << 3) + (ch - '0');
          }
        }
        buf_c(&str, x & 0xff);   /* JS keeps values > 255 as UTF-16 units; not in this document */
        break;
      }
      case '\r':
        ch = st_lookchar(s);
        if (ch == '\n') st_skip(s, 1);
        break;
      case '\n':
        break;
      default:
        buf_c(&str, ch);
      }
      break;
    default:
      buf_c(&str, ch);
    }
  } while (!done);
  return O_str(buf_view(&str), T_STR);
}

static Obj lex_getname(Lexer *L, int ch) {
  Buf str = {0};
  Stream *s = L->s;
  while ((ch = st_lookchar(s)) >= 0 && !k_special[ch]) {
    st_skip(s, 1);
    if (ch == '#') {
      ch = st_lookchar(s);
      int x = tohexdigit(ch);
      if (x != -1) {
        st_skip(s, 1);
        int x2 = tohexdigit(st_getchar(s));
        if (x2 == -1) die("Illegal digit in hex char in name");
        buf_c(&str, (x << 4) | x2);
      } else {
        buf_c(&str, '#');
        buf_c(&str, ch);
      }
    } else {
      buf_c(&str, ch);
    }
  }
  if (str.n > 128) die("name token is longer than allowed by the spec");
  return O_str(buf_view(&str), T_NAME);
}

static Obj lex_gethexstring(Lexer *L, int ch) {
  Buf str = {0};
  Stream *s = L->s;
  (void)ch;
  for (;;) {
    ch = st_getchar(s);
    if (ch == '>') break;
    if (ch < 0) break;
    if (k_special[ch] != 1) {
      int x = tohexdigit(ch);
      if (x == -1) die("Illegal character in hex string");
      ch = st_getchar(s);
      while (ch >= 0 && k_special[ch] == 1) ch = st_getchar(s);
      if (ch < 0) die("Illegal character in hex string");
      int x2 = tohexdigit(ch);
      if (x2 == -1) die("Illegal character in hex string");
      buf_c(&str, (x << 4) | x2);
    }
  }
  return O_str(buf_view(&str), T_STR);
}

static Obj cmd_obj(const char *name) { return O_str(bytes_copy((const uint8_t *)name, (int)strlen(name)), T_CMD); }
static Obj cmd_bytes(Bytes b) { return O_str(b, T_CMD); }

static Obj lex_getobj(Lexer *L) {
  Stream *s = L->s;
  int comment = 0;
  int ch;
  for (;;) {
    ch = st_getchar(s);
    if (ch < 0) return O_of(T_EOF);
    if (comment) {
      if (ch == '\r' || ch == '\n') comment = 0;
    } else if (ch == '%') {
      comment = 1;
    } else if (k_special[ch] != 1) {
      break;
    }
  }
  switch (ch) {
  case '0': case '1': case '2': case '3': case '4':
  case '5': case '6': case '7': case '8': case '9':
  case '+': case '-': case '.':
    return lex_getnumber(L, ch);
  case '(':
    return lex_getstring(L);
  case '/':
    return lex_getname(L, ch);
  case '[':
  case ']': {
    char c[2] = {(char)ch, 0};
    return cmd_obj(c);
  }
  case '<':
    ch = st_lookchar(s);
    if (ch == '<') {
      st_skip(s, 1);
      return cmd_obj("<<");
    }
    return lex_gethexstring(L, ch);
  case '>':
    ch = st_lookchar(s);
    if (ch == '>') {
      st_skip(s, 1);
      return cmd_obj(">>");
    }
    /* falls through (as in the JS) */
  case '{':
  case '}': {
    char c[2] = {(char)ch, 0};
    return cmd_obj(c);
  }
  case ')':
    die("Illegal character: )");
  }
  /* command token */
  Buf str = {0};
  buf_c(&str, ch);
  while ((ch = st_lookchar(s)) >= 0 && !k_special[ch]) {
    st_skip(s, 1);
    if (str.n == 128) die("Command token too long");
    buf_c(&str, ch);
  }
  Bytes t = buf_view(&str);
  if (bytes_eq(t, "true")) {
    Obj o = O_of(T_BOOL);
    o.n = 1;
    return o;
  }
  if (bytes_eq(t, "false")) return O_of(T_BOOL);
  if (bytes_eq(t, "null")) return O_of(T_NULL);
  return cmd_bytes(t);
}

static void lex_skip_to_next_line(Lexer *L) {
  Stream *s = L->s;
  for (;;) {
    int ch = st_getchar(s);
    if (ch < 0 || ch == '\n') return;
    if (ch == '\r') {
      if ((ch = st_lookchar(s)) == '\n') st_skip(s, 1);
      return;
    }
  }
}

