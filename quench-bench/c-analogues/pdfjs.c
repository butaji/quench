typedef struct { uint32_t *codes; int maxLen; } HTab;
static HTab fixed_lit, fixed_dist;

/* generateHuffmanTable(lengths): canonical codes, bit-reversed, replicated. */
static HTab huff_table(const uint8_t *lengths, int n) {
  int maxLen = 0;
  for (int i = 0; i < n; ++i)
    if (lengths[i] > maxLen) maxLen = lengths[i];
  int size = 1 << maxLen;
  uint32_t *codes = aalloc(sizeof(uint32_t) * (size_t)size);
  uint32_t code = 0, skip = 2;
  for (int len = 1; len <= maxLen; ++len, code <<= 1, skip <<= 1) {
    for (int val = 0; val < n; ++val) {
      if (lengths[val] == len) {
        uint32_t code2 = 0, t = code;
        for (int i = 0; i < len; ++i) {
          code2 = (code2 << 1) | (t & 1);
          t >>= 1;
        }
        for (uint32_t i = code2; i < (uint32_t)size; i += skip)
          codes[i] = ((uint32_t)len << 16) | (uint32_t)val;
        ++code;
      }
    }
  }
  HTab t = {codes, maxLen};
  return t;
}

static uint32_t g_fixed_lit_codes[512], g_fixed_dist_codes[32];

/* The fixed Huffman tables are built once, outside the per-iteration arena. */
static void flate_init_tables(void) {
  uint8_t l[288];
  for (int i = 0; i < 144; i++) l[i] = 8;
  for (int i = 144; i < 256; i++) l[i] = 9;
  for (int i = 256; i < 280; i++) l[i] = 7;
  for (int i = 280; i < 288; i++) l[i] = 8;
  fixed_lit = huff_table(l, 288);
  uint8_t d[32];
  for (int i = 0; i < 32; i++) d[i] = 5;
  fixed_dist = huff_table(d, 32);
  memcpy(g_fixed_lit_codes, fixed_lit.codes, sizeof g_fixed_lit_codes);
  memcpy(g_fixed_dist_codes, fixed_dist.codes, sizeof g_fixed_dist_codes);
  fixed_lit.codes = g_fixed_lit_codes;
  fixed_dist.codes = g_fixed_dist_codes;
}

static void ds_ensure(Stream *s, int requested) {
  int current = s->bufCap;
  if (requested < current) return;
  int size = 512;
  while (size < requested) size <<= 1;
  uint8_t *b2 = aalloc((size_t)size);
  if (current) memcpy(b2, s->buf, (size_t)current);
  s->buf = b2;
  s->bufCap = size;
}

static uint32_t flate_getbits(Stream *s, int bits) {
  int codeSize = s->codeSize;
  uint32_t codeBuf = s->codeBuf;
  int bytesPos = s->bytesPos;
  while (codeSize < bits) {
    if (bytesPos >= s->blen) die("Bad encoding in flate stream");
    codeBuf |= (uint32_t)s->bytes[bytesPos++] << codeSize;
    codeSize += 8;
  }
  uint32_t b = codeBuf & ((1u << bits) - 1);
  s->codeBuf = codeBuf >> bits;
  s->codeSize = codeSize - bits;
  s->bytesPos = bytesPos;
  return b;
}

static uint32_t flate_getcode(Stream *s, const HTab *t) {
  uint32_t *codes = t->codes;
  int maxLen = t->maxLen;
  int codeSize = s->codeSize;
  uint32_t codeBuf = s->codeBuf;
  int bytesPos = s->bytesPos;
  while (codeSize < maxLen) {
    if (bytesPos >= s->blen) die("Bad encoding in flate stream");
    codeBuf |= (uint32_t)s->bytes[bytesPos++] << codeSize;
    codeSize += 8;
  }
  uint32_t code = codes[codeBuf & ((1u << maxLen) - 1)];
  int codeLen = (int)(code >> 16);
  uint32_t codeVal = code & 0xffff;
  if (codeSize == 0 || codeSize < codeLen || codeLen == 0) die("Bad encoding in flate stream");
  s->codeBuf = codeBuf >> codeLen;
  s->codeSize = codeSize - codeLen;
  s->bytesPos = bytesPos;
  return codeVal;
}

static void flate_read_block(Stream *s) {
  uint32_t hdr = flate_getbits(s, 3);
  if (hdr & 1) s->eof = 1;
  hdr >>= 1;

  if (hdr == 0) { /* uncompressed block */
    int bytesPos = s->bytesPos;
    if (bytesPos >= s->blen) die("Bad block header in flate stream");
    int blockLen = s->bytes[bytesPos++];
    if (bytesPos >= s->blen) die("Bad block header in flate stream");
    blockLen |= s->bytes[bytesPos++] << 8;
    if (bytesPos >= s->blen) die("Bad block header in flate stream");
    int check = s->bytes[bytesPos++];
    if (bytesPos >= s->blen) die("Bad block header in flate stream");
    check |= s->bytes[bytesPos++] << 8;
    if (check != (~blockLen & 0xffff)) die("Bad uncompressed block length in flate stream");
    s->codeBuf = 0;
    s->codeSize = 0;
    int bufferLength = s->bufLen;
    ds_ensure(s, bufferLength + blockLen);
    int end = bufferLength + blockLen;
    s->bufLen = end;
    for (int n = bufferLength; n < end; ++n) {
      if (bytesPos >= s->blen) {
        s->eof = 1;
        break;
      }
      s->buf[n] = s->bytes[bytesPos++];
    }
    s->bytesPos = bytesPos;
    return;
  }

  HTab litTab, distTab;
  if (hdr == 1) {
    litTab = fixed_lit;
    distTab = fixed_dist;
  } else if (hdr == 2) { /* dynamic codes */
    int numLitCodes = (int)flate_getbits(s, 5) + 257;
    int numDistCodes = (int)flate_getbits(s, 5) + 1;
    int numCodeLenCodes = (int)flate_getbits(s, 4) + 4;
    uint8_t codeLenCodeLengths[19];
    memset(codeLenCodeLengths, 0, sizeof codeLenCodeLengths);
    for (int i = 0; i < numCodeLenCodes; ++i)
      codeLenCodeLengths[k_codelen_map[i]] = (uint8_t)flate_getbits(s, 3);
    HTab codeLenCodeTab = huff_table(codeLenCodeLengths, 19);

    int len = 0, i = 0;
    int codes = numLitCodes + numDistCodes;
    uint8_t *codeLengths = aalloc((size_t)codes);
    while (i < codes) {
      int code = (int)flate_getcode(s, &codeLenCodeTab);
      int bitsLength, bitsOffset, what;
      if (code == 16) {
        bitsLength = 2; bitsOffset = 3; what = len;
      } else if (code == 17) {
        bitsLength = 3; bitsOffset = 3; len = 0; what = 0;
      } else if (code == 18) {
        bitsLength = 7; bitsOffset = 11; len = 0; what = 0;
      } else {
        codeLengths[i++] = (uint8_t)(len = code);
        continue;
      }
      int repeatLength = (int)flate_getbits(s, bitsLength) + bitsOffset;
      while (repeatLength-- > 0) codeLengths[i++] = (uint8_t)what;
    }
    litTab = huff_table(codeLengths, numLitCodes);
    distTab = huff_table(codeLengths + numLitCodes, numDistCodes);
  } else {
    die("Unknown block type in flate stream");
  }

  uint8_t *buffer = s->buf;
  int limit = s->buf ? s->bufCap : 0;
  int pos = s->bufLen;
  for (;;) {
    uint32_t code1 = flate_getcode(s, &litTab);
    if (code1 < 256) {
      if (pos + 1 >= limit) {
        ds_ensure(s, pos + 1);
        buffer = s->buf;
        limit = s->bufCap;
      }
      buffer[pos++] = (uint8_t)code1;
      continue;
    }
    if (code1 == 256) {
      s->bufLen = pos;
      return;
    }
    code1 -= 257;
    if (code1 >= 29) die("bad length code");
    code1 = k_length_decode[code1];
    uint32_t code2 = code1 >> 16;
    if (code2 > 0) code2 = flate_getbits(s, (int)code2);
    int len = (int)((code1 & 0xffff) + code2);
    code1 = flate_getcode(s, &distTab);
    if (code1 >= 30) die("bad distance code");
    code1 = k_dist_decode[code1];
    code2 = code1 >> 16;
    if (code2 > 0) code2 = flate_getbits(s, (int)code2);
    int dist = (int)((code1 & 0xffff) + code2);
    if (pos + len >= limit) {
      ds_ensure(s, pos + len);
      buffer = s->buf;
      limit = s->bufCap;
    }
    for (int k = 0; k < len; ++k, ++pos) buffer[pos] = buffer[pos - dist];
  }
}

/* new FlateStream(stream): header checks, then a DecodeStream over the bytes. */
static Stream *g_flate_list[64];   /* FlateStreams in creation order (validation) */
static int g_flate_n;

static Stream *flate_new(Stream *parent) {
  Bytes bytes = st_getbytes(parent, 0);
  Stream *s = aalloc(sizeof(Stream));
  if (g_flate_n >= 64) die("too many flate streams");
  g_flate_list[g_flate_n++] = s;
  s->flate = 1;
  s->dict = parent->dict;
  s->bytes = bytes.p;
  s->blen = bytes.n;
  int cmf = bytes.n > 0 ? bytes.p[0] : -1;
  int flg = bytes.n > 1 ? bytes.p[1] : -1;
  if (cmf == -1 || flg == -1) die("Invalid header in flate stream");
  if ((cmf & 0x0f) != 0x08) die("Unknown compression method in flate stream");
  if ((((cmf << 8) + flg) % 31) != 0) die("Bad FCHECK in flate stream");
  if (flg & 0x20) die("FDICT bit set in flate stream");
  s->bytesPos = 2;
  s->codeSize = 0;
  s->codeBuf = 0;
  return s;
}

