/* Arena: all per-iteration objects (like the JS heap) are bump-allocated and  */
/* released together at the start of the next iteration.                       */

#define ARENA_BYTES ((size_t)128 << 20)
static uint8_t *g_arena;
static size_t g_arena_used;

static void *aalloc(size_t n) {
  n = (n + 15) & ~(size_t)15;
  if (n == 0) n = 16;
  if (g_arena_used + n > ARENA_BYTES) die("arena exhausted");
  void *p = g_arena + g_arena_used;
  g_arena_used += n;
  memset(p, 0, n);
  return p;
}

typedef struct { const uint8_t *p; int n; } Bytes;

static Bytes B(const char *s) {
  Bytes b = {(const uint8_t *)s, (int)strlen(s)};
  return b;
}
static int bytes_eq(Bytes a, const char *s) {
  int n = (int)strlen(s);
  return a.n == n && memcmp(a.p, s, (size_t)n) == 0;
}
static int bytes_eqb(Bytes a, Bytes b) {
  return a.n == b.n && memcmp(a.p, b.p, (size_t)a.n) == 0;
}
static Bytes bytes_copy(const uint8_t *p, int n) {
  uint8_t *q = aalloc((size_t)n + 1);
  if (n) memcpy(q, p, (size_t)n);
  Bytes b = {q, n};
  return b;
}

/* Growable byte buffer (JS string or array being built). */
typedef struct { uint8_t *p; int n, cap; } Buf;

static void buf_reserve(Buf *b, int extra) {
  if (b->n + extra <= b->cap) return;
  int nc = b->cap ? b->cap * 2 : 256;
  while (nc < b->n + extra) nc *= 2;
  uint8_t *np = aalloc((size_t)nc);
  if (b->n) memcpy(np, b->p, (size_t)b->n);
  b->p = np;
  b->cap = nc;
}
static void buf_put(Buf *b, const void *s, int n) {
  buf_reserve(b, n);
  if (n) memcpy(b->p + b->n, s, (size_t)n);
  b->n += n;
}
static void buf_c(Buf *b, int c) {
  buf_reserve(b, 1);
  b->p[b->n++] = (uint8_t)c;
}
#define BUF_LIT(b, s) buf_put((b), (s), (int)sizeof(s) - 1)
static Bytes buf_view(const Buf *b) {
  Bytes r = {b->p, b->n};
  return r;
}

/* JS ToInt32 on a double. */
static int32_t js_i32(double d) {
  if (d >= -2147483648.0 && d <= 2147483647.0) return (int32_t)d;
  if (d != d || d - d != 0.0) return 0;
  d = fmod(trunc(d), 4294967296.0);
  if (d < 0) d += 4294967296.0;
  return (int32_t)(uint32_t)d;
}
/* JS: value is an int32 (x|0 == x). */
static int js_isint(double v) {
  return v >= -2147483648.0 && v <= 2147483647.0 && v == (double)(int32_t)v;
}
/* string16 / string32 / safeString16 of the PDF.js helpers. */
static void put16(Buf *b, double v) {
  int32_t x = js_i32(v);
  buf_c(b, (x >> 8) & 0xff);
  buf_c(b, x & 0xff);
}
static void put32(Buf *b, double v) {
  uint32_t x = (uint32_t)js_i32(v);
  buf_c(b, (x >> 24) & 0xff);
  buf_c(b, (x >> 16) & 0xff);
  buf_c(b, (x >> 8) & 0xff);
  buf_c(b, x & 0xff);
}
static void putsafe16(Buf *b, double v) {
  v = v > 0x7FFF ? 0x7FFF : v < -0x8000 ? -0x8000 : v;
  put16(b, v);
}

/* Simple string-keyed hash map (JS object used as a dictionary). */
typedef struct { Bytes *keys; intptr_t *vals; uint8_t *used; int cap, n; } StrMap;
static uint32_t fnv(const uint8_t *p, int n) {
  uint32_t h = 2166136261u;
  for (int i = 0; i < n; i++) h = (h ^ p[i]) * 16777619u;
  return h;
}
static void smap_init(StrMap *m, int cap) {
  int c = 16;
  while (c < cap) c <<= 1;
  cap = c;
  m->cap = cap;
  m->n = 0;
  m->keys = aalloc(sizeof(Bytes) * (size_t)cap);
  m->vals = aalloc(sizeof(intptr_t) * (size_t)cap);
  m->used = aalloc((size_t)cap);
}
static int smap_find(const StrMap *m, Bytes k, intptr_t **slot) {
  uint32_t h = fnv(k.p, k.n) & (uint32_t)(m->cap - 1);
  for (;;) {
    if (!m->used[h]) { *slot = &m->vals[h]; return 0; }
    if (bytes_eqb(m->keys[h], k)) { *slot = &m->vals[h]; return 1; }
    h = (h + 1) & (uint32_t)(m->cap - 1);
  }
}
static void smap_grow(StrMap *m);
static void smap_set(StrMap *m, Bytes k, intptr_t v) {
  intptr_t *slot;
  if (smap_find(m, k, &slot)) { *slot = v; return; }
  if ((m->n + 1) * 2 > m->cap) {
    smap_grow(m);
    smap_find(m, k, &slot);
  }
  uint32_t h = fnv(k.p, k.n) & (uint32_t)(m->cap - 1);
  while (m->used[h]) h = (h + 1) & (uint32_t)(m->cap - 1);
  m->used[h] = 1;
  m->keys[h] = k;
  m->vals[h] = v;
  m->n++;
}
static void smap_grow(StrMap *m) {
  StrMap old = *m;
  smap_init(m, old.cap * 2);
  for (int i = 0; i < old.cap; i++)
    if (old.used[i]) smap_set(m, old.keys[i], old.vals[i]);
}
/* Returns 1 and sets *v if present. */
static int smap_get(const StrMap *m, Bytes k, intptr_t *v) {
  intptr_t *slot;
  if (!smap_find(m, k, &slot)) return 0;
  *v = *slot;
  return 1;
}

