/* Objects: the PDF.js object model (Name, Cmd, Dict, Ref, arrays, streams).   */

enum {
  T_UNDEF, T_NULL, T_BOOL, T_NUM, T_STR, T_NAME, T_CMD, T_EOF, T_REF, T_ARR,
  T_DICT, T_STREAM
};

typedef struct Obj {
  uint8_t t;
  int num, gen;    /* T_REF */
  double n;        /* T_NUM, T_BOOL */
  Bytes s;         /* T_STR, T_NAME, T_CMD */
  void *p;         /* T_ARR (Arr*), T_DICT (Dict*), T_STREAM (Stream*) */
} Obj;

typedef struct Arr { Obj *a; int n, cap; } Arr;

typedef struct XRef XRef;
typedef struct Dict Dict;
typedef struct Stream Stream;

static Obj O_undef(void) { Obj o; memset(&o, 0, sizeof o); return o; }
static Obj O_of(uint8_t t) { Obj o; memset(&o, 0, sizeof o); o.t = t; return o; }
static Obj O_num(double v) { Obj o = O_of(T_NUM); o.n = v; return o; }
static Obj O_str(Bytes s, uint8_t t) { Obj o = O_of(t); o.s = s; return o; }
static Obj O_ref(int num, int gen) { Obj o = O_of(T_REF); o.num = num; o.gen = gen; return o; }
static Obj O_p(uint8_t t, void *p) { Obj o = O_of(t); o.p = p; return o; }

static void arr_push(Arr *a, Obj v) {
  if (a->n == a->cap) {
    int nc = a->cap ? a->cap * 2 : 8;
    Obj *na = aalloc(sizeof(Obj) * (size_t)nc);
    if (a->n) memcpy(na, a->a, sizeof(Obj) * (size_t)a->n);
    a->a = na;
    a->cap = nc;
  }
  a->a[a->n++] = v;
}
static Arr *arr_new(void) { return aalloc(sizeof(Arr)); }

static int is_cmd(Obj o, const char *name) { return o.t == T_CMD && bytes_eq(o.s, name); }
static int is_eof(Obj o) { return o.t == T_EOF; }
static int is_int(Obj o) { return o.t == T_NUM && js_isint(o.n); }
static int is_num(Obj o) { return o.t == T_NUM; }
static int is_name(Obj o) { return o.t == T_NAME; }
static int is_dict(Obj o) { return o.t == T_DICT; }
static int is_arr(Obj o) { return o.t == T_ARR; }
static int is_stream(Obj o) { return o.t == T_STREAM; }
static int is_ref(Obj o) { return o.t == T_REF; }
static int is_string(Obj o) { return o.t == T_STR; }

/* Dict: insertion-ordered key/value pairs (JS object keys in insertion order). */
struct Dict {
  XRef *xref;      /* NULL for dicts made without an xref */
  int n, cap;
  Bytes *k;
  Obj *v;
  void *translated;   /* font dicts: font.translated */
  Bytes loadedName;   /* font dicts: font.loadedName */
  int hasLoadedName;
};

static Dict *dict_new(XRef *x) {
  Dict *d = aalloc(sizeof(Dict));
  d->xref = x;
  return d;
}
static int dict_find(const Dict *d, const char *key) {
  int n = (int)strlen(key);
  for (int i = 0; i < d->n; i++)
    if (d->k[i].n == n && memcmp(d->k[i].p, key, (size_t)n) == 0) return i;
  return -1;
}
static void dict_set_b(Dict *d, Bytes key, Obj v) {
  for (int i = 0; i < d->n; i++)
    if (bytes_eqb(d->k[i], key)) { d->v[i] = v; return; }
  if (d->n == d->cap) {
    int nc = d->cap ? d->cap * 2 : 8;
    Bytes *nk = aalloc(sizeof(Bytes) * (size_t)nc);
    Obj *nv = aalloc(sizeof(Obj) * (size_t)nc);
    if (d->n) {
      memcpy(nk, d->k, sizeof(Bytes) * (size_t)d->n);
      memcpy(nv, d->v, sizeof(Obj) * (size_t)d->n);
    }
    d->k = nk;
    d->v = nv;
    d->cap = nc;
  }
  d->k[d->n] = key;
  d->v[d->n] = v;
  d->n++;
}

static Obj fetch_if_ref(XRef *x, Obj v);
static Obj xref_fetch(XRef *x, Obj ref);

/* Dict.get(key1, key2, key3): the JS fallback order, with fetchIfRef. */
static Obj dict_get3(const Dict *d, const char *k1, const char *k2, const char *k3) {
  int i = dict_find(d, k1);
  if (i >= 0 || !k2) {
    Obj v = i >= 0 ? d->v[i] : O_undef();
    return d->xref ? fetch_if_ref(d->xref, v) : v;
  }
  i = dict_find(d, k2);
  if (i >= 0 || !k3) {
    Obj v = i >= 0 ? d->v[i] : O_undef();
    return d->xref ? fetch_if_ref(d->xref, v) : v;
  }
  i = dict_find(d, k3);
  Obj v = i >= 0 ? d->v[i] : O_of(T_NULL);
  if (i >= 0 && (v.t == T_NULL || (v.t == T_BOOL && v.n == 0) ||
                 (v.t == T_NUM && (v.n == 0 || v.n != v.n)) || (v.t == T_STR && v.s.n == 0)))
    v = O_of(T_NULL);
  return d->xref ? fetch_if_ref(d->xref, v) : v;
}
static Obj dict_get(const Dict *d, const char *k) { return dict_get3(d, k, NULL, NULL); }
static int dict_has(const Dict *d, const char *k) { return dict_find(d, k) >= 0; }

