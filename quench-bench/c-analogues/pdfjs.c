/* Streams: Stream (plain bytes view) and FlateStream (DecodeStream subclass).  */

struct Stream {
  int flate;              /* 0: Stream, 1: FlateStream */
  const uint8_t *bytes;   /* plain: whole buffer; flate: compressed input view */
  int blen;
  int start, end, pos;    /* plain: start/end; both: read position */
  Dict *dict;
  /* DecodeStream state */
  uint8_t *buf;
  int bufCap, bufLen, eof;
  /* FlateStream state */
  int bytesPos;
  uint32_t codeBuf;
  int codeSize;
};

static Stream *st_plain(const uint8_t *bytes, int blen, int start, int length, Dict *d) {
  /* new Stream(arrayBuffer, start, length, dict): end = (start + length) || bytes.length */
  Stream *s = aalloc(sizeof(Stream));
  s->bytes = bytes;
  s->blen = blen;
  s->start = start;
  s->pos = start;
  int end = length < 0 ? 0 : start + length;   /* length < 0: undefined (NaN) */
  s->end = end ? end : blen;
  s->dict = d;
  return s;
}
/* Stream over a copy of a typed array (new Uint8Array(typedArray) copies). */

static void flate_read_block(Stream *s);
static void ds_ensure(Stream *s, int requested);

/* Stream.getBytes(length) / DecodeStream.getBytes(length); length 0 means "all". */
static Bytes st_getbytes(Stream *s, int length) {
  Bytes r;
  if (!s->flate) {
    if (!length) {
      r.p = s->bytes + s->pos;
      r.n = s->end - s->pos;
      return r;
    }
    int pos = s->pos, end = pos + length;
    if (end > s->end) end = s->end;
    s->pos = end;
    r.p = s->bytes + pos;
    r.n = end - pos;
    return r;
  }
  int end, pos = s->pos;
  if (length) {
    ds_ensure(s, pos + length);
    end = pos + length;
    while (!s->eof && s->bufLen < end) flate_read_block(s);
    if (end > s->bufLen) end = s->bufLen;
  } else {
    while (!s->eof) flate_read_block(s);
    end = s->bufLen;
    if (!end) {
      s->buf = aalloc(1);
      s->bufCap = 0;
    }
  }
  s->pos = end;
  r.p = s->buf + pos;
  r.n = end - pos;
  return r;
}

/* lookChar / getChar return the byte, or -1 for null. */
static int st_lookchar(Stream *s) {
  if (!s->flate) {
    if (s->pos >= s->end) return -1;
    return s->bytes[s->pos];
  }
  int pos = s->pos;
  while (s->bufLen <= pos) {
    if (s->eof) return -1;
    flate_read_block(s);
  }
  return s->buf[s->pos];
}
static int st_getchar(Stream *s) {
  if (!s->flate) {
    if (s->pos >= s->end) return -1;
    return s->bytes[s->pos++];
  }
  int pos = s->pos;
  while (s->bufLen <= pos) {
    if (s->eof) return -1;
    flate_read_block(s);
  }
  return s->buf[s->pos++];
}
static void st_skip(Stream *s, int n) {
  if (!n) n = 1;
  s->pos += n;
}
static void st_reset(Stream *s) { s->pos = s->flate ? 0 : s->start; }
static void st_movestart(Stream *s) { s->start = s->pos; }

/* Stream.makeSubStream / DecodeStream.makeSubStream (plain case only). */
static Stream *st_substream(Stream *s, int start, int length, Dict *d) {
  if (s->flate) die("makeSubStream on a decoded stream is not used by this document");
  return st_plain(s->bytes, s->blen, start, length, d);
}

