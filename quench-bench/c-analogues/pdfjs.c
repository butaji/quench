static void xref_cache_set(XRef *x, int num, Obj v) {
  if (num >= x->capcache) {
    int nc = x->capcache ? x->capcache : 64;
    while (nc <= num) nc *= 2;
    Obj *nv = aalloc(sizeof(Obj) * (size_t)nc);
    uint8_t *nh = aalloc((size_t)nc);
    if (x->capcache) {
      memcpy(nv, x->cache, sizeof(Obj) * (size_t)x->capcache);
      memcpy(nh, x->cachehas, (size_t)x->capcache);
    }
    x->cache = nv;
    x->cachehas = nh;
    x->capcache = nc;
  }
  x->cache[num] = v;
  x->cachehas[num] = 1;
}

static void xref_entry_set(XRef *x, int num, XEntry e) {
  if (num >= x->capent) {
    int nc = x->capent ? x->capent : 64;
    while (nc <= num) nc *= 2;
    XEntry *ne = aalloc(sizeof(XEntry) * (size_t)nc);
    if (x->capent) memcpy(ne, x->ent, sizeof(XEntry) * (size_t)x->capent);
    x->ent = ne;
    x->capent = nc;
  }
  x->ent[num] = e;
  if (num >= x->nent) x->nent = num + 1;
}

/* XRef.readXRefTable */
static Dict *xref_read_table(XRef *x, Parser *parser) {
  (void)x;
  Obj obj;
  for (;;) {
    obj = parser_getobj(parser);
    if (is_cmd(obj, "trailer")) break;
    Obj first = obj;
    Obj count = parser_getobj(parser);
    if (!is_int(first) || !is_int(count)) die("Invalid XRef table: wrong types in subsection header");
    for (int i = 0; i < (int)count.n; i++) {
      XEntry e;
      memset(&e, 0, sizeof e);
      Obj offset = parser_getobj(parser);
      Obj gen = parser_getobj(parser);
      Obj type = parser_getobj(parser);
      e.present = 1;
      if (is_cmd(type, "f")) e.free = 1;
      else if (is_cmd(type, "n")) e.uncompressed = 1;
      if (!is_int(offset) || !is_int(gen) || !(e.free || e.uncompressed))
        die("Invalid entry in XRef subsection");
      e.offset = (int)offset.n;
      e.gen = (int)gen.n;
      int idx = i + (int)first.n;
      if (!(idx < x->nent && x->ent[idx].present)) xref_entry_set(x, idx, e);
    }
  }
  if (x->nent > 0 && x->ent[0].present && !x->ent[0].free) die("Invalid XRef table: unexpected first object");
  if (!is_cmd(obj, "trailer")) die("Invalid XRef table: could not find trailer dictionary");
  Obj dict = parser_getobj(parser);
  if (!is_dict(dict)) die("Invalid XRef table: could not parse trailer dictionary");
  return dict.p;
}

/* XRef.readXRef(startXRef) for classic tables (the only form in this document). */
static Dict *xref_read_xref(XRef *x, int startXRef) {
  Stream *stream = x->stream;
  stream->pos = startXRef;
  Parser *parser = parser_new(stream, 1, NULL);
  Obj obj = parser_getobj(parser);
  if (!is_cmd(obj, "xref")) die("unsupported XRef form (only classic tables are used)");
  Dict *dict = xref_read_table(x, parser);
  if (dict_has(dict, "XRefStm") || dict_has(dict, "Prev")) die("hybrid/previous xref sections are not used");
  return dict;
}

static Obj fetch_if_ref(XRef *x, Obj v) {
  if (!is_ref(v)) return v;
  return xref_fetch(x, v);
}

/* XRef.fetch(ref) */
static Obj xref_fetch(XRef *x, Obj ref) {
  int num = ref.num;
  if (num < x->capcache && x->cachehas[num]) return x->cache[num];
  if (num >= x->nent || !x->ent[num].present) die("bad XRef entry (no entry)");
  XEntry e = x->ent[num];
  if (e.free) {
    Obj nul = O_of(T_NULL);
    xref_cache_set(x, num, nul);
    return nul;
  }
  int gen = ref.gen;
  if (!e.uncompressed) die("compressed objects are not used by this document");
  if (e.gen != gen) die("inconsistent generation in XRef");
  Stream *stream = st_substream(x->stream, e.offset, -1, NULL);
  Parser *parser = parser_new(stream, 1, x);
  Obj obj1 = parser_getobj(parser);
  Obj obj2 = parser_getobj(parser);
  Obj obj3 = parser_getobj(parser);
  if (!is_int(obj1) || obj1.n != num || !is_int(obj2) || obj2.n != gen || obj3.t != T_CMD)
    die("bad XRef entry");
  if (!is_cmd(obj3, "obj")) die("bad XRef entry");
  Obj val = parser_getobj(parser);
  if (!is_stream(val)) xref_cache_set(x, num, val);
  return val;
}


/* Catalog */
typedef struct Page Page;
typedef struct Catalog {
  XRef *xref;
  Dict *catDict;
  Page **pages;
  int npages, cappages;
} Catalog;

struct Page {
  int pageNumber;
  Dict *pageDict;
  XRef *xref;
  Obj ref;
};

static Catalog *catalog_new(XRef *x) {
  Catalog *c = aalloc(sizeof(Catalog));
  c->xref = x;
  Obj obj = x->root;
  if (!is_dict(obj)) die("catalog object is not a dictionary");
  c->catDict = obj.p;
  return c;
}

static Obj page_inherit(const Page *pg, const char *key) {
  Dict *dict = pg->pageDict;
  Obj obj = dict_get(dict, key);
  while (obj.t == T_UNDEF) {
    Obj parent = dict_get(dict, "Parent");
    if (!is_dict(parent)) break;
    dict = parent.p;
    obj = dict_get(dict, key);
  }
  return obj;
}

static void catalog_traverse_kids(Catalog *c, Dict *pagesDict) {
  Obj kids = dict_get(pagesDict, "Kids");
  if (!is_arr(kids)) die("page dictionary kids object is not an array");
  Arr *ka = kids.p;
  for (int i = 0; i < ka->n; ++i) {
    Obj kid = ka->a[i];
    if (!is_ref(kid)) die("page dictionary kid is not a reference");
    Obj obj = xref_fetch(c->xref, kid);
    if ((is_dict(obj) && dict_has(obj.p, "Type") && bytes_eq(dict_get(obj.p, "Type").s, "Page")) ||
        (is_dict(obj) && !dict_has(obj.p, "Kids"))) {
      if (c->npages == c->cappages) {
        int nc = c->cappages ? c->cappages * 2 : 4;
        Page **np = aalloc(sizeof(Page *) * (size_t)nc);
        if (c->npages) memcpy(np, c->pages, sizeof(Page *) * (size_t)c->npages);
        c->pages = np;
        c->cappages = nc;
      }
      Page *pg = aalloc(sizeof(Page));
      pg->pageNumber = c->npages;
      pg->pageDict = obj.p;
      pg->xref = c->xref;
      pg->ref = kid;
      c->pages[c->npages++] = pg;
    } else {
      if (!is_dict(obj)) die("page dictionary kid reference points to wrong type of object");
      catalog_traverse_kids(c, obj.p);
    }
  }
}

static Page *catalog_get_page(Catalog *c, int n) {
  if (c->npages == 0) {
    Obj pagesObj = dict_get(c->catDict, "Pages");
    if (!is_dict(pagesObj)) die("invalid top-level pages dictionary");
    catalog_traverse_kids(c, pagesObj.p);
  }
  return c->pages[n - 1];
}

