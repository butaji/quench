// jetstream-files: Octane/pdfjs.js
// iterations: 120
// jetstream-driver: deterministic=true
/* C analogue of JetStream's Octane/pdfjs.js (PDF.js build 3cc61f0 run by the
 * benchmark's mock browser). Each runIteration() opens the embedded 110920-byte
 * PDF, parses its xref, trailer, catalog and page tree, decodes the page content
 * stream and the nine embedded Type 1 font programs (FlateDecode), converts each
 * font to an OpenType/CFF file, then runs the content stream through the
 * PartialEvaluator and the CanvasGraphics interpreter, which logs every mock
 * canvas call. The per-iteration work is the same as the JS: the same object
 * parsing, the same stream reads, the same charstring decoding, the same table
 * building (cmap/OS2/post/name/head/hhea/hmtx/maxp, CFF writer), the same base64
 * of each font for the @font-face rule, the same glyph cache and the same log.
 *
 * The PDF bytes are embedded (support/pdfjs-data.h, generated by
 * tools/pdfjs-extract.cjs from getPDF(); the JS decodes base64 once at setup, not
 * per iteration). Constant tables (GlyphsUnicode, Encodings, CFF standard strings,
 * PDFStringTranslateTable, UnicodeRanges) come from support/pdfjs-tables.h.
 *
 * Validation (tools/pdfjs-validate.cjs run under node 22 with instrumented copies
 * of the JS): after the first and last timed iterations the canvas log must have 36788 items and
 * the JS hash of join(" ") must be 939524096 (the JS hash only reads a prefix of
 * the string, so a full-string FNV-1a is also checked against the node value), the
 * nine font programs must have the byte counts and checksums node produces, and
 * the work counters (parser objects, glyph lookups, charstrings decoded, flate
 * output sizes, operator-list entries) must equal node's. The check runs after the
 * timer, as the JetStream driver never calls the JS tearDown.
 *
 * Simplifications, all of which leave the output and the per-operation work
 * unchanged: promises and the fake worker message queue are direct calls, the
 * setTimeout-based flushing happens in call order, the operator-list time slicing
 * (Date.now() > endTime) never triggers at this size, and the DOM/CSS mock calls
 * (createElement, insertRule, addEventListener) are reduced to their data flow.
 * Only the operators, filters and font types used by this document are implemented;
 * anything else aborts with an error (as the JS does for unknown operators).
 *
 * Timing: main() runs argv[1] (default 120) iterations, timing only the
 * iterations; prints "pdfjs <n> iterations <ms> ms" and "validation ok"/"validation
 * FAILED". argv[2] (JetStream root) is accepted for the common driver interface but
 * unused: the PDF is embedded.
 *
 * Measured on this machine, 120 iterations: C 302-360 ms (validation ok); node 22
 * running the same loop (instrumented copy of the composed row, timed with
 * performance.now()) 2155-2597 ms.
 */
