/* PDFDocument: header search, startxref, linearization probe, numPages.       */

typedef struct { Stream *stream; XRef *xref; Catalog *catalog; } PDFDoc;

/* find(stream, needle, limit, backwards): searches the next `limit` bytes. */
static int pdf_find(Stream *stream, const char *needle, int limit, int backwards) {
  int pos = stream->pos;
  int end = stream->end;
  int m = (int)strlen(needle);
  if (pos + limit > end) limit = end - pos;
  Buf str = {0};
  for (int n = 0; n < limit; ++n) buf_c(&str, st_getchar(stream));
  stream->pos = pos;
  int index = -1;
  if (backwards) {
    for (int i = str.n - m; i >= 0; i--)
      if (memcmp(str.p + i, needle, (size_t)m) == 0) { index = i; break; }
  } else {
    for (int i = 0; i + m <= str.n; i++)
      if (memcmp(str.p + i, needle, (size_t)m) == 0) { index = i; break; }
  }
  if (index == -1) return 0;
  stream->pos += index;
  return 1;
}

/* Linearization probe: parses the first object and checks /Linearized. */
static int linearization_length(Stream *stream) {
  Parser *p = parser_new(stream, 0, NULL);
  Obj obj1 = parser_getobj(p);
  Obj obj2 = parser_getobj(p);
  Obj obj3 = parser_getobj(p);
  Obj linDict = parser_getobj(p);
  if (is_int(obj1) && is_int(obj2) && is_cmd(obj3, "obj") && is_dict(linDict)) {
    Obj o = dict_get(linDict.p, "Linearized");
    if (!(is_num(o) && o.n > 0)) linDict.t = T_NULL;
  }
  if (!is_dict(linDict)) return 0;   /* linearization.length getter: 0 */
  return 0;
}

static int pdf_start_xref(PDFDoc *doc) {
  Stream *stream = doc->stream;
  /* linearization check: the document is not linearized, so the length check fails */
  int linearized = 0;
  (void)linearized;
  stream->pos = stream->pos;  /* the probe reads from the current position (after checkHeader) */
  (void)linearization_length(stream);
  int startXRef = 0;
  int step = 1024;
  int found = 0, pos = stream->end;
  while (!found && pos > 0) {
    pos -= step - 9;   /* 'startxref'.length */
    if (pos < 0) pos = 0;
    stream->pos = pos;
    found = pdf_find(stream, "startxref", step, 1);
  }
  if (found) {
    st_skip(stream, 9);
    int ch;
    do {
      ch = st_getchar(stream);
    } while (ch == ' ' || ch == '\t' || ch == '\r' || ch == '\n');
    Buf str = {0};
    /* (ch - '0') <= 9 : digits, and whitespace (ToNumber gives 0) */
    while (ch >= 0 && ((ch >= '0' && ch <= '9') || ch == ' ' || ch == '\t' || ch == '\r' || ch == '\n' || ch == '\v' || ch == '\f')) {
      buf_c(&str, ch);
      ch = st_getchar(stream);
    }
    /* parseInt(str, 10) */
    long v = 0;
    int i = 0;
    while (i < str.n && (str.p[i] == ' ' || str.p[i] == '\t' || str.p[i] == '\r' || str.p[i] == '\n')) i++;
    while (i < str.n && str.p[i] >= '0' && str.p[i] <= '9') v = v * 10 + (str.p[i++] - '0');
    startXRef = (int)v;
  }
  return startXRef;
}

static void pdf_open(PDFDoc *doc, const uint8_t *data, int len) {
  Stream *stream = st_plain(data, len, 0, -1, NULL);
  doc->stream = stream;
  /* checkHeader */
  st_reset(stream);
  if (pdf_find(stream, "%PDF-", 1024, 0)) st_movestart(stream);
  int startXRef = pdf_start_xref(doc);
  XRef *x = aalloc(sizeof(XRef));
  x->stream = stream;
  doc->xref = x;
  Dict *trailer = xref_read_xref(x, startXRef);
  trailer->xref = x;
  x->trailer = trailer;
  Obj root = dict_get(trailer, "Root");
  if (!is_dict(root)) die("Invalid root reference");
  x->root = root;
  doc->catalog = catalog_new(x);
  /* PDFDocument.getDocumentInfo: fetches /Info and converts its string values */
  if (dict_has(trailer, "Info")) {
    Obj infoObj = dict_get(trailer, "Info");
    if (is_dict(infoObj)) {
      Dict *idict = infoObj.p;
      for (int i = 0; i < idict->n; i++) {
        Obj v = idict->v[i];
        if (v.t == T_STR) {
          Buf conv = {0};   /* stringToPDFString: one pass over the bytes */
          for (int k = 0; k < v.s.n; k++) buf_c(&conv, v.s.p[k]);
        }
      }
    }
  }
  if (dict_has(doc->catalog->catDict, "AcroForm")) dict_get(doc->catalog->catDict, "AcroForm");
}

