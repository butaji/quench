static Obj fetch_parser_ref(Parser *P, Obj v) {
  if (!is_ref(v)) return v;
  if (!P->xref) die("Parser has no xref");
  return xref_fetch(P->xref, v);
}

static void parser_refill(Parser *P) {
  P->buf1 = lex_getobj(&P->lx);
  P->buf2 = lex_getobj(&P->lx);
}
static void parser_shift(Parser *P) {
  if (is_cmd(P->buf2, "ID")) {
    P->buf1 = P->buf2;
    P->buf2 = O_of(T_NULL);
    st_skip(P->lx.s, 1);
  } else {
    P->buf1 = P->buf2;
    P->buf2 = lex_getobj(&P->lx);
  }
}

static Parser *parser_new(Stream *s, int allowStreams, XRef *x) {
  Parser *P = aalloc(sizeof(Parser));
  P->lx.s = s;
  P->allowStreams = allowStreams;
  P->xref = x;
  parser_refill(P);
  return P;
}

static Stream *parser_make_stream(Parser *P, Dict *dict);
static Obj parser_getobj(Parser *P);

static Obj parser_getobj(Parser *P) {
  g_count_getobj++;
  if (is_cmd(P->buf1, "BI")) die("inline images are not used by this document");
  if (is_cmd(P->buf1, "[")) {
    parser_shift(P);
    Arr *array = arr_new();
    while (!is_cmd(P->buf1, "]") && !is_eof(P->buf1)) arr_push(array, parser_getobj(P));
    if (is_eof(P->buf1)) die("End of file inside array");
    parser_shift(P);
    return O_p(T_ARR, array);
  }
  if (is_cmd(P->buf1, "<<")) {
    parser_shift(P);
    Dict *dict = dict_new(P->xref);
    while (!is_cmd(P->buf1, ">>") && !is_eof(P->buf1)) {
      if (!is_name(P->buf1)) die("Dictionary key must be a name object");
      Bytes key = P->buf1.s;
      parser_shift(P);
      if (is_eof(P->buf1)) break;
      Obj v = parser_getobj(P);
      dict_set_b(dict, key, v);
    }
    if (is_eof(P->buf1)) die("End of file inside dictionary");
    if (is_cmd(P->buf2, "stream")) {
      return P->allowStreams ? O_p(T_STREAM, parser_make_stream(P, dict)) : O_p(T_DICT, dict);
    }
    parser_shift(P);
    return O_p(T_DICT, dict);
  }
  if (is_int(P->buf1)) {
    int num = (int)P->buf1.n;
    parser_shift(P);
    if (is_int(P->buf1) && is_cmd(P->buf2, "R")) {
      Obj ref = O_ref(num, (int)P->buf1.n);
      parser_shift(P);
      parser_shift(P);
      return ref;
    }
    return O_num(num);
  }
  if (is_string(P->buf1)) {
    Obj str = P->buf1;
    parser_shift(P);
    return str;
  }
  Obj obj = P->buf1;
  parser_shift(P);
  return obj;
}

/* Parser.makeStream: the data is found after the 'stream' keyword's line. */
static Stream *parser_filter(Parser *P, Stream *stream, Dict *dict, int length);

static Stream *parser_make_stream(Parser *P, Dict *dict) {
  Stream *stream = P->lx.s;
  lex_skip_to_next_line(&P->lx);
  int pos = stream->pos;
  Obj lenObj = fetch_parser_ref(P, dict_get(dict, "Length"));
  if (!is_int(lenObj)) die("Bad Length attribute in stream");
  int length = (int)lenObj.n;
  stream->pos = pos + length;
  parser_shift(P);   /* '>>' -> 'stream' */
  parser_shift(P);   /* 'stream' -> 'endstream' */
  if (!is_cmd(P->buf1, "endstream")) die("Missing endstream");
  parser_shift(P);
  Stream *sub = st_substream(stream, pos, length, dict);
  return parser_filter(P, sub, dict, length);
}

static Stream *parser_filter(Parser *P, Stream *stream, Dict *dict, int length) {
  (void)length;
  Obj filter = dict_get3(dict, "Filter", "F", NULL);
  Obj params = dict_get3(dict, "DecodeParms", "DP", NULL);
  params = fetch_parser_ref(P, params);
  if (is_name(filter)) {
    if (bytes_eq(filter.s, "FlateDecode") || bytes_eq(filter.s, "Fl")) {
      if (params.t == T_DICT && params.p) die("PredictorStream is not used by this document");
      if (params.t != T_UNDEF && params.t != T_NULL) die("PredictorStream is not used by this document");
      Stream *f = flate_new(stream);
      f->dict = stream->dict;
      return f;
    }
    die("unsupported stream filter for this document");
  }
  if (is_arr(filter)) die("filter arrays are not used by this document");
  return stream;
}

