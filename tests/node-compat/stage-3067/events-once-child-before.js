"use strict";
const assert = require("assert");
require("child_process");
const { once, EventEmitter, listenerCount } = require("events");
const emitter = new EventEmitter();
const controller = new AbortController();
assert.strictEqual(typeof controller.signal, "object");
const expected = new Error("boom");
process.nextTick(() => emitter.emit("error", expected));
const pending = once(emitter, "value", { signal: controller.signal });
assert.strictEqual(emitter.listenerCount("error"), 1);
assert.strictEqual(listenerCount(controller.signal, "abort"), 1);
pending.then(() => assert.fail("resolved"), (error) => assert.strictEqual(error, expected));
