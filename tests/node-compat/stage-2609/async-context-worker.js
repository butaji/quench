"use strict";
const assert = require("assert");
const { AsyncLocalStorage } = require("node:async_hooks");
const storage = new AsyncLocalStorage({ defaultValue: "default" });
assert.strictEqual(storage.getStore(), "default");
assert.strictEqual(storage.run("outer", () => storage.run("inner", () => storage.getStore())), "inner");
assert.strictEqual(storage.getStore(), "default");
storage.enterWith({ value: 1 });
assert.strictEqual(storage.getStore().value, 1);
assert.strictEqual(storage.exit(() => storage.getStore().value), 1);
assert.strictEqual(storage.getStore().value, 1);
storage.disable();
assert.strictEqual(storage.getStore(), undefined);
console.log("ok");
